"""
Stage 1: ChainTree Data Handle - Loader and organizer.

Loads the JSON (or YAML) file generated by the Lua DSL frontend and provides
organized access to all data needed for the downstream pipeline stages.

Supports two input formats:
  - Structured JSON (schema_version >= "1.0"): nodes under "nodes" key,
    event/bitmask tables as top-level keys
  - Legacy flat format (YAML or JSON without schema_version): nodes and
    metadata mixed at top level
"""

import json
from pathlib import Path
from typing import Dict, List, Optional, Set


class ChainTreeHandle:
    """
    Handle object for ChainTree pipeline data.
    Loads and organizes data for the header generation pipeline.
    """
    
    def __init__(self, input_file: Path):
        self.input_file = input_file
        
        # Load based on file extension
        with open(input_file, 'r') as f:
            if input_file.suffix in ('.yaml', '.yml'):
                try:
                    import yaml
                    self.raw_data = yaml.safe_load(f)
                except ImportError:
                    raise ImportError(
                        "PyYAML required for .yaml files. "
                        "Install with: pip install pyyaml\n"
                        "Or use JSON format instead (recommended)."
                    )
            else:
                self.raw_data = json.load(f)
        
        # Detect format and normalize
        self.schema_version = self.raw_data.get('schema_version', None)
        
        if self.schema_version:
            self._load_structured()
        else:
            self._load_legacy()
        
        # Organized storage (populated by _parse)
        self.kb_nodes: Dict[str, Dict[str, Dict]] = {}
        self.kb_root_nodes: Dict[str, str] = {}
        self.special_table_nodes: Set[str] = set()
        
        # Function collections
        self.all_main_functions: Set[str] = set()
        self.all_one_shot_functions: Set[str] = set()
        self.all_boolean_functions: Set[str] = set()
        
        self._parse_nodes()

    def _load_structured(self) -> None:
        """Load from structured JSON format (schema_version >= 1.0)."""
        self.kb_log_dict = self.raw_data.get('kb_log_dict', {})
        self.ltree_to_index = self.raw_data.get('ltree_to_index', {})
        self.total_nodes = self.raw_data.get('total_nodes', 0)
        self.kb_metadata = self.raw_data.get('kb_metadata', {})
        self.event_string_table = self.raw_data.get('event_string_table', {})
        self.bitmask_table = self.raw_data.get('bitmask_table', {})
        
        # Nodes are under the "nodes" key
        self._node_source = self.raw_data.get('nodes', {})
    
    def _load_legacy(self) -> None:
        """Load from legacy flat format (old YAML or unversioned JSON)."""
        self.kb_log_dict = self.raw_data.get('kb_log_dict', {})
        self.ltree_to_index = self.raw_data.get('ltree_to_index', {})
        self.total_nodes = self.raw_data.get('total_nodes', 0)
        self.kb_metadata = self.raw_data.get('kb_metadata', {})
        self.event_string_table = {}
        self.bitmask_table = {}
        
        # In legacy format, nodes are mixed with metadata at top level
        # We'll extract them during _parse_nodes and also find event/bitmask tables
        self._node_source = None  # Signal to use raw_data directly

    def _parse_nodes(self) -> None:
        """Parse node data into organized structures."""
        
        # Determine source of node entries
        if self._node_source is not None:
            # Structured format: nodes are pre-separated
            node_entries = self._node_source.items()
        else:
            # Legacy format: filter metadata keys from raw_data
            metadata_keys = {'kb_log_dict', 'ltree_to_index', 'total_nodes', 'kb_metadata'}
            node_entries = (
                (k, v) for k, v in self.raw_data.items()
                if k not in metadata_keys and isinstance(v, dict)
            )
        
        for ltree_name, node_data in node_entries:
            if not isinstance(node_data, dict):
                continue
            
            parts = ltree_name.split('.')
            if len(parts) < 2 or parts[0] != 'kb':
                continue
            
            kb_name = parts[1]
            
            # Handle special table KBs (only needed for legacy format)
            if self._node_source is None:
                if kb_name == 'event_string_table_kb':
                    if 'node_dict' in node_data:
                        self.event_string_table = node_data['node_dict'].copy()
                    self.special_table_nodes.add(ltree_name)
                    continue
                
                if kb_name == 'bitmask_table_kb':
                    if 'node_dict' in node_data:
                        self.bitmask_table = node_data['node_dict'].copy()
                    self.special_table_nodes.add(ltree_name)
                    continue
            
            # Regular node
            if kb_name not in self.kb_nodes:
                self.kb_nodes[kb_name] = {}
            
            self.kb_nodes[kb_name][ltree_name] = node_data
            
            if kb_name not in self.kb_root_nodes or len(ltree_name) < len(self.kb_root_nodes[kb_name]):
                self.kb_root_nodes[kb_name] = ltree_name
            
            # Collect function names
            if 'label_dict' in node_data:
                label_dict = node_data['label_dict']
                
                main_fn = label_dict.get('main_function_name')
                if main_fn and main_fn != 'CFL_NULL':
                    self.all_main_functions.add(main_fn)
                
                init_fn = label_dict.get('initialization_function_name')
                term_fn = label_dict.get('termination_function_name')
                if init_fn and init_fn != 'CFL_NULL':
                    self.all_one_shot_functions.add(init_fn)
                if term_fn and term_fn != 'CFL_NULL':
                    self.all_one_shot_functions.add(term_fn)
                
                aux_fn = label_dict.get('aux_function_name')
                if aux_fn and aux_fn != 'CFL_NULL':
                    self.all_boolean_functions.add(aux_fn)
    
    # =========================================================================
    # Query Methods - Knowledge Bases
    # =========================================================================

    def get_kb_metadata(self, kb_name: str, key: str, default=None):
        return self.kb_metadata.get(kb_name, {}).get(key, default)

    def get_all_kb_metadata(self, kb_name: str) -> Dict:
        return self.kb_metadata.get(kb_name, {})
    
    def get_kb_node_aliases(self, kb_name: str) -> Dict[str, int]:
        return self.kb_metadata.get(kb_name, {}).get('node_aliases', {})
    
    def get_kb_names(self) -> List[str]:
        return list(self.kb_nodes.keys())
    
    def get_kb_node_count(self, kb_name: str) -> int:
        return len(self.kb_nodes.get(kb_name, {}))
    
    def get_kb_root_node(self, kb_name: str) -> Optional[str]:
        return self.kb_root_nodes.get(kb_name)
    
    def get_kb_nodes(self, kb_name: str) -> Dict[str, Dict]:
        return self.kb_nodes.get(kb_name, {})
    
    # =========================================================================
    # Query Methods - Nodes
    # =========================================================================
    
    def get_node_data(self, ltree_name: str) -> Optional[Dict]:
        for kb_nodes in self.kb_nodes.values():
            if ltree_name in kb_nodes:
                return kb_nodes[ltree_name]
        return None
    
    def get_node_index(self, ltree_name: str) -> Optional[int]:
        return self.ltree_to_index.get(ltree_name)
    
    def get_node_parent(self, ltree_name: str) -> Optional[str]:
        node_data = self.get_node_data(ltree_name)
        if node_data and 'label_dict' in node_data:
            return node_data['label_dict'].get('parent_ltree_name')
        return None
    
    def get_node_children(self, ltree_name: str) -> List[str]:
        node_data = self.get_node_data(ltree_name)
        if node_data and 'label_dict' in node_data:
            return node_data['label_dict'].get('links') or []
        return []
    
    def get_node_label(self, ltree_name: str) -> Optional[str]:
        node_data = self.get_node_data(ltree_name)
        if node_data:
            return node_data.get('label')
        return None
    
    def get_node_name(self, ltree_name: str) -> Optional[str]:
        node_data = self.get_node_data(ltree_name)
        if node_data:
            return node_data.get('node_name')
        return None
    
    # =========================================================================
    # Query Methods - Functions
    # =========================================================================
    
    def get_node_functions(self, ltree_name: str) -> Dict[str, str]:
        node_data = self.get_node_data(ltree_name)
        if not node_data or 'label_dict' not in node_data:
            return {}
        
        label_dict = node_data['label_dict']
        return {
            'main': label_dict.get('main_function_name', 'CFL_NULL'),
            'init': label_dict.get('initialization_function_name', 'CFL_NULL'),
            'aux': label_dict.get('aux_function_name', 'CFL_NULL'),
            'term': label_dict.get('termination_function_name', 'CFL_NULL')
        }
    
    def get_all_functions(self) -> Dict[str, Set[str]]:
        return {
            'main': self.all_main_functions.copy(),
            'one_shot': self.all_one_shot_functions.copy(),
            'boolean': self.all_boolean_functions.copy()
        }
    
    # =========================================================================
    # Query Methods - Event/Bitmask Tables
    # =========================================================================
    
    def get_event_string_table(self) -> Dict[str, int]:
        return self.event_string_table.copy()
    
    def get_bitmask_table(self) -> Dict[str, int]:
        return self.bitmask_table.copy()
    
    def has_event_table(self) -> bool:
        return len(self.event_string_table) > 0
    
    def has_bitmask_table(self) -> bool:
        return len(self.bitmask_table) > 0
    
    # =========================================================================
    # Traversal Methods
    # =========================================================================
    
    def traverse_kb_breadth_first(self, kb_name: str) -> List[str]:
        root = self.get_kb_root_node(kb_name)
        if not root:
            return []
        
        result = []
        queue = [root]
        visited = set()
        
        while queue:
            current = queue.pop(0)
            if current in visited:
                continue
            visited.add(current)
            result.append(current)
            
            children = self.get_node_children(current)
            for child in children:
                if child not in visited:
                    queue.append(child)
        
        return result
    
    def traverse_kb_depth_first(self, kb_name: str) -> List[str]:
        root = self.get_kb_root_node(kb_name)
        if not root:
            return []
        
        result = []
        visited = set()
        
        def dfs(node: str):
            if node in visited:
                return
            visited.add(node)
            result.append(node)
            for child in self.get_node_children(node):
                dfs(child)
        
        dfs(root)
        return result
    
    # =========================================================================
    # Validation & Summary
    # =========================================================================
    
    def validate(self) -> List[str]:
        errors = []
        
        for ltree_name, index in self.ltree_to_index.items():
            node_data = self.get_node_data(ltree_name)
            if not node_data and ltree_name not in self.special_table_nodes:
                errors.append(f"Node in ltree_to_index not found in data: {ltree_name}")
        
        for kb_name, kb_nodes in self.kb_nodes.items():
            for ltree_name, node_data in kb_nodes.items():
                if 'label_dict' in node_data:
                    parent = node_data['label_dict'].get('parent_ltree_name')
                    if not parent or parent == '':
                        continue
                    parent_parts = parent.split('.')
                    if len(parent_parts) <= 2:
                        continue
                    if not self.get_node_data(parent):
                        errors.append(f"Invalid parent reference in {ltree_name}: {parent}")
                    
                    children = node_data['label_dict'].get('links') or []
                    for child in children:
                        if not self.get_node_data(child):
                            errors.append(f"Invalid child reference in {ltree_name}: {child}")
        
        actual_indexed = len(self.ltree_to_index)
        if self.total_nodes != actual_indexed:
            errors.append(
                f"total_nodes mismatch: declared={self.total_nodes}, "
                f"indexed in ltree_to_index={actual_indexed}"
            )
        
        actual_in_kb_nodes = sum(len(nodes) for nodes in self.kb_nodes.values())
        if actual_indexed != actual_in_kb_nodes + len(self.special_table_nodes):
            errors.append(
                f"Index count inconsistency: ltree_to_index has {actual_indexed} entries, "
                f"but kb_nodes has {actual_in_kb_nodes} + {len(self.special_table_nodes)} special = "
                f"{actual_in_kb_nodes + len(self.special_table_nodes)} nodes"
            )
        
        return errors
    
    def print_summary(self) -> None:
        fmt = "JSON" if self.schema_version else "Legacy"
        ver = f" v{self.schema_version}" if self.schema_version else ""
        
        print("=" * 70)
        print(f"Stage 1: ChainTree Handle Summary ({fmt}{ver})")
        print("=" * 70)
        print(f"Input File: {self.input_file}")
        print(f"Total Nodes: {self.total_nodes}")
        print(f"Knowledge Bases: {len(self.kb_nodes)}")
        
        for kb_name in self.kb_nodes.keys():
            node_count = self.get_kb_node_count(kb_name)
            root_node = self.get_kb_root_node(kb_name)
            aliases = self.get_kb_node_aliases(kb_name)
            alias_info = f", {len(aliases)} aliases" if aliases else ""
            print(f"  - {kb_name}: {node_count} nodes, root={root_node}{alias_info}")
        
        print(f"\nFunctions:")
        print(f"  Main functions: {len(self.all_main_functions)}")
        print(f"  One-shot functions: {len(self.all_one_shot_functions)}")
        print(f"  Boolean functions: {len(self.all_boolean_functions)}")
        
        if self.has_event_table():
            print(f"\nEvent String Table: {len(self.event_string_table)} events")
        if self.has_bitmask_table():
            print(f"Bitmask Table: {len(self.bitmask_table)} bitmasks")
        
        errors = self.validate()
        if errors:
            print(f"\n⚠ Validation Errors ({len(errors)}):")
            for error in errors:
                print(f"  - {error}")
        else:
            print("\n✓ Validation passed")
        print("=" * 70)


# Backward compatibility alias
ChainTreeYamlHandle = ChainTreeHandle