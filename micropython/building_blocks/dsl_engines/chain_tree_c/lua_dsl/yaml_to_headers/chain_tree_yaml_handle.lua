--[[
    ChainTreeYamlHandle - Data loader and organizer for header generation pipeline.

    This class loads the YAML file generated by ChainTreeYaml and provides
    organized access to all data needed for C header generation.

    Translated from Python to LuaJIT.

    Dependencies:
      - lyaml (required for loading YAML files)
]]

local ChainTreeYamlHandle = {}
ChainTreeYamlHandle.__index = ChainTreeYamlHandle

-- ---------------------------------------------------------------------------
-- Utility helpers
-- ---------------------------------------------------------------------------

--- Shallow copy a table (one level deep).
local function shallow_copy(t)
    if t == nil then return {} end
    local out = {}
    for k, v in pairs(t) do out[k] = v end
    return out
end

--- Count the number of keys in a table (for hash-style tables).
local function table_len(t)
    local n = 0
    for _ in pairs(t) do n = n + 1 end
    return n
end

--- Collect sorted keys from a table.
local function sorted_keys(t)
    local keys = {}
    for k, _ in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

--- Collect keys sorted by their values (ascending).
local function keys_sorted_by_value(t)
    local items = {}
    for k, v in pairs(t) do items[#items + 1] = { key = k, val = v } end
    table.sort(items, function(a, b) return a.val < b.val end)
    return items
end

-- Try to load a YAML library
local yaml_lib
local ok, lyaml = pcall(require, "lyaml")
if ok then
    yaml_lib = lyaml
end

-- ---------------------------------------------------------------------------
-- Constructor
-- ---------------------------------------------------------------------------

function ChainTreeYamlHandle.new(yaml_file)
    local self = setmetatable({}, ChainTreeYamlHandle)

    self.yaml_file = yaml_file

    -- Load raw YAML data
    local f = io.open(yaml_file, "r")
    if not f then
        error("Cannot open YAML file: " .. yaml_file)
    end
    local content = f:read("*a")
    f:close()

    if yaml_lib then
        self.raw_data = yaml_lib.load(content)
    else
        error("lyaml library is required to load YAML files. Install with: luarocks install lyaml")
    end

    if type(self.raw_data) ~= "table" then
        error("Failed to parse YAML file or file is empty: " .. yaml_file)
    end

    -- Extract top-level metadata
    self.kb_log_dict = self.raw_data.kb_log_dict or {}
    self.ltree_to_index = self.raw_data.ltree_to_index or {}
    self.total_nodes = self.raw_data.total_nodes or 0
    self.kb_metadata = self.raw_data.kb_metadata or {}

    -- Organize nodes by knowledge base
    self.kb_nodes = {}          -- kb_name -> {ltree_name -> node_data}
    self.kb_root_nodes = {}     -- kb_name -> root_ltree_name

    -- Track special table nodes that are extracted separately
    self.special_table_nodes = {}   -- set: ltree_name -> true

    -- Event and bitmask tables
    self.event_string_table = {}    -- event_id -> index
    self.bitmask_table = {}         -- event_name -> bit_number

    -- Function collections (all unique functions across all KBs)
    self.all_main_functions = {}        -- set: fn_name -> true
    self.all_one_shot_functions = {}    -- set: fn_name -> true
    self.all_boolean_functions = {}     -- set: fn_name -> true

    -- Parse the YAML structure
    self:_parse_yaml_data()

    return self
end

-- ---------------------------------------------------------------------------
-- Internal: Parse YAML data
-- ---------------------------------------------------------------------------

function ChainTreeYamlHandle:_parse_yaml_data()
    -- Metadata keys to skip
    local skip_keys = {
        kb_log_dict = true,
        ltree_to_index = true,
        total_nodes = true,
        kb_metadata = true,
    }

    for ltree_name, node_data in pairs(self.raw_data) do
        -- Skip metadata entries
        if skip_keys[ltree_name] then
            goto continue
        end

        -- Skip non-table entries
        if type(node_data) ~= "table" then
            goto continue
        end

        -- Parse ltree path
        local parts = {}
        for part in ltree_name:gmatch("[^%.]+") do
            parts[#parts + 1] = part
        end

        if #parts < 2 or parts[1] ~= "kb" then
            goto continue
        end

        local kb_name = parts[2]

        -- Check for special tables
        if kb_name == "event_string_table_kb" then
            self:_extract_event_string_table(ltree_name, node_data)
            self.special_table_nodes[ltree_name] = true
            goto continue
        end

        if kb_name == "bitmask_table_kb" then
            self:_extract_bitmask_table(ltree_name, node_data)
            self.special_table_nodes[ltree_name] = true
            goto continue
        end

        -- Initialize KB storage if needed
        if not self.kb_nodes[kb_name] then
            self.kb_nodes[kb_name] = {}
        end

        -- Store node data
        self.kb_nodes[kb_name][ltree_name] = node_data

        -- Track root node (shortest path for each KB)
        if not self.kb_root_nodes[kb_name]
           or #ltree_name < #self.kb_root_nodes[kb_name] then
            self.kb_root_nodes[kb_name] = ltree_name
        end

        -- Collect function names
        if node_data.label_dict then
            local label_dict = node_data.label_dict

            local main_fn = label_dict.main_function_name
            if main_fn and main_fn ~= "CFL_NULL" then
                self.all_main_functions[main_fn] = true
            end

            local init_fn = label_dict.initialization_function_name
            local term_fn = label_dict.termination_function_name
            if init_fn and init_fn ~= "CFL_NULL" then
                self.all_one_shot_functions[init_fn] = true
            end
            if term_fn and term_fn ~= "CFL_NULL" then
                self.all_one_shot_functions[term_fn] = true
            end

            local aux_fn = label_dict.aux_function_name
            if aux_fn and aux_fn ~= "CFL_NULL" then
                self.all_boolean_functions[aux_fn] = true
            end
        end

        ::continue::
    end
end

-- ---------------------------------------------------------------------------
-- Validation
-- ---------------------------------------------------------------------------

function ChainTreeYamlHandle:validate()
    local errors = {}

    -- Check that all nodes in ltree_to_index exist in data OR are special tables
    for ltree_name, index in pairs(self.ltree_to_index) do
        local node_data = self:get_node_data(ltree_name)
        if not node_data and not self.special_table_nodes[ltree_name] then
            errors[#errors + 1] = "Node in ltree_to_index not found in data: " .. ltree_name
        end
    end

    -- Check that all parent references are valid
    for kb_name, kb_nodes in pairs(self.kb_nodes) do
        for ltree_name, node_data in pairs(kb_nodes) do
            if node_data.label_dict then
                local parent = node_data.label_dict.parent_ltree_name

                -- Skip validation for root nodes (parent is just KB name with <=2 parts)
                if not parent or parent == "" then
                    goto next_node
                end

                local parent_parts = {}
                for part in parent:gmatch("[^%.]+") do
                    parent_parts[#parent_parts + 1] = part
                end

                if #parent_parts <= 2 then
                    -- This is a KB-level parent (e.g., "kb.first_test")
                    -- These are valid for root nodes, skip validation
                    goto next_node
                end

                -- Check if parent exists in data
                if not self:get_node_data(parent) then
                    errors[#errors + 1] = "Invalid parent reference in " .. ltree_name .. ": " .. parent
                end

                -- Check that all children exist
                local children = node_data.label_dict.links or {}
                for _, child in ipairs(children) do
                    if not self:get_node_data(child) then
                        errors[#errors + 1] = "Invalid child reference in " .. ltree_name .. ": " .. child
                    end
                end
            end

            ::next_node::
        end
    end

    -- Validate total_nodes against ltree_to_index (the authoritative count)
    local actual_indexed = table_len(self.ltree_to_index)

    if self.total_nodes ~= actual_indexed then
        errors[#errors + 1] = string.format(
            "total_nodes mismatch: declared=%d, indexed in ltree_to_index=%d",
            self.total_nodes, actual_indexed
        )
    end

    -- Also report the breakdown for information
    local actual_in_kb_nodes = 0
    for _, nodes in pairs(self.kb_nodes) do
        actual_in_kb_nodes = actual_in_kb_nodes + table_len(nodes)
    end
    local special_count = table_len(self.special_table_nodes)

    if actual_indexed ~= actual_in_kb_nodes + special_count then
        errors[#errors + 1] = string.format(
            "Index count inconsistency: ltree_to_index has %d entries, "
            .. "but kb_nodes has %d + %d special = %d nodes",
            actual_indexed, actual_in_kb_nodes, special_count,
            actual_in_kb_nodes + special_count
        )
    end

    return errors
end

-- ---------------------------------------------------------------------------
-- Internal: Extract special tables
-- ---------------------------------------------------------------------------

function ChainTreeYamlHandle:_extract_event_string_table(ltree_name, node_data)
    if node_data.node_dict then
        self.event_string_table = shallow_copy(node_data.node_dict)
    end
end

function ChainTreeYamlHandle:_extract_bitmask_table(ltree_name, node_data)
    if node_data.node_dict then
        self.bitmask_table = shallow_copy(node_data.node_dict)
    end
end

-- =========================================================================
-- Query Methods - Knowledge Bases
-- =========================================================================

function ChainTreeYamlHandle:get_kb_metadata(kb_name, key, default)
    local kb_meta = self.kb_metadata[kb_name]
    if not kb_meta then return default end
    if key == nil then return kb_meta end
    local val = kb_meta[key]
    if val == nil then return default end
    return val
end

function ChainTreeYamlHandle:get_all_kb_metadata(kb_name)
    return self.kb_metadata[kb_name] or {}
end

function ChainTreeYamlHandle:get_kb_node_aliases(kb_name)
    local kb_info = self.kb_metadata[kb_name]
    if not kb_info then return {} end
    return kb_info.node_aliases or {}
end

function ChainTreeYamlHandle:get_kb_names()
    local names = {}
    for kb_name, _ in pairs(self.kb_nodes) do
        names[#names + 1] = kb_name
    end
    return names
end

function ChainTreeYamlHandle:get_kb_node_count(kb_name)
    local nodes = self.kb_nodes[kb_name]
    if not nodes then return 0 end
    return table_len(nodes)
end

function ChainTreeYamlHandle:get_kb_root_node(kb_name)
    return self.kb_root_nodes[kb_name]
end

function ChainTreeYamlHandle:get_kb_nodes(kb_name)
    return self.kb_nodes[kb_name] or {}
end

-- =========================================================================
-- Query Methods - Nodes
-- =========================================================================

function ChainTreeYamlHandle:get_node_data(ltree_name)
    for _, kb_nodes in pairs(self.kb_nodes) do
        if kb_nodes[ltree_name] then
            return kb_nodes[ltree_name]
        end
    end
    return nil
end

function ChainTreeYamlHandle:get_node_index(ltree_name)
    return self.ltree_to_index[ltree_name]
end

function ChainTreeYamlHandle:get_node_parent(ltree_name)
    local node_data = self:get_node_data(ltree_name)
    if node_data and node_data.label_dict then
        return node_data.label_dict.parent_ltree_name
    end
    return nil
end

function ChainTreeYamlHandle:get_node_children(ltree_name)
    local node_data = self:get_node_data(ltree_name)
    if node_data and node_data.label_dict then
        return node_data.label_dict.links or {}
    end
    return {}
end

function ChainTreeYamlHandle:get_node_label(ltree_name)
    local node_data = self:get_node_data(ltree_name)
    if node_data then
        return node_data.label
    end
    return nil
end

function ChainTreeYamlHandle:get_node_name(ltree_name)
    local node_data = self:get_node_data(ltree_name)
    if node_data then
        return node_data.node_name
    end
    return nil
end

-- =========================================================================
-- Query Methods - Functions
-- =========================================================================

function ChainTreeYamlHandle:get_node_functions(ltree_name)
    local node_data = self:get_node_data(ltree_name)
    if not node_data or not node_data.label_dict then
        return {}
    end

    local label_dict = node_data.label_dict
    return {
        main = label_dict.main_function_name or "CFL_NULL",
        init = label_dict.initialization_function_name or "CFL_NULL",
        aux = label_dict.aux_function_name or "CFL_NULL",
        term = label_dict.termination_function_name or "CFL_NULL",
    }
end

function ChainTreeYamlHandle:get_all_functions()
    return {
        main = shallow_copy(self.all_main_functions),
        one_shot = shallow_copy(self.all_one_shot_functions),
        boolean = shallow_copy(self.all_boolean_functions),
    }
end

-- =========================================================================
-- Query Methods - Event/Bitmask Tables
-- =========================================================================

function ChainTreeYamlHandle:get_event_string_table()
    return shallow_copy(self.event_string_table)
end

function ChainTreeYamlHandle:get_bitmask_table()
    return shallow_copy(self.bitmask_table)
end

function ChainTreeYamlHandle:has_event_table()
    return next(self.event_string_table) ~= nil
end

function ChainTreeYamlHandle:has_bitmask_table()
    return next(self.bitmask_table) ~= nil
end

-- =========================================================================
-- Traversal Methods
-- =========================================================================

function ChainTreeYamlHandle:traverse_kb_breadth_first(kb_name)
    local root = self:get_kb_root_node(kb_name)
    if not root then
        return {}
    end

    local result = {}
    local queue = { root }
    local visited = {}  -- set

    while #queue > 0 do
        local current = table.remove(queue, 1)

        if visited[current] then
            goto next_bfs
        end

        visited[current] = true
        result[#result + 1] = current

        -- Add children to queue
        local children = self:get_node_children(current)
        for _, child in ipairs(children) do
            if not visited[child] then
                queue[#queue + 1] = child
            end
        end

        ::next_bfs::
    end

    return result
end

function ChainTreeYamlHandle:traverse_kb_depth_first(kb_name)
    local root = self:get_kb_root_node(kb_name)
    if not root then
        return {}
    end

    local result = {}
    local visited = {}  -- set

    local function dfs(node)
        if visited[node] then
            return
        end

        visited[node] = true
        result[#result + 1] = node

        -- Visit children
        local children = self:get_node_children(node)
        for _, child in ipairs(children) do
            dfs(child)
        end
    end

    dfs(root)
    return result
end

-- =========================================================================
-- Statistics
-- =========================================================================

function ChainTreeYamlHandle:get_statistics()
    local stats = {
        total_nodes = self.total_nodes,
        kb_count = table_len(self.kb_nodes),
        kb_details = {},
        function_counts = {
            main = table_len(self.all_main_functions),
            one_shot = table_len(self.all_one_shot_functions),
            boolean = table_len(self.all_boolean_functions),
        },
        event_count = table_len(self.event_string_table),
        bitmask_count = table_len(self.bitmask_table),
    }

    for kb_name, _ in pairs(self.kb_nodes) do
        stats.kb_details[kb_name] = {
            node_count = self:get_kb_node_count(kb_name),
            root_node = self:get_kb_root_node(kb_name),
        }
    end

    return stats
end

-- =========================================================================
-- Print Summary
-- =========================================================================

function ChainTreeYamlHandle:print_summary()
    local sep = string.rep("=", 70)

    print(sep)
    print("ChainTree YAML Handle Summary")
    print(sep)
    print("YAML File: " .. self.yaml_file)
    print("Total Nodes: " .. self.total_nodes)
    print("Knowledge Bases: " .. table_len(self.kb_nodes))

    for kb_name, _ in pairs(self.kb_nodes) do
        local node_count = self:get_kb_node_count(kb_name)
        local root_node = self:get_kb_root_node(kb_name) or "nil"
        local aliases = self:get_kb_node_aliases(kb_name)
        local alias_count = table_len(aliases)
        local alias_info = ""
        if alias_count > 0 then
            alias_info = ", " .. alias_count .. " aliases"
        end
        print(string.format("  - %s: %d nodes, root=%s%s",
            kb_name, node_count, root_node, alias_info))
    end

    print("")
    print("Functions:")
    print("  Main functions: " .. table_len(self.all_main_functions))
    print("  One-shot functions: " .. table_len(self.all_one_shot_functions))
    print("  Boolean functions: " .. table_len(self.all_boolean_functions))

    if self:has_event_table() then
        print("")
        print("Event String Table: " .. table_len(self.event_string_table) .. " events")
    end

    if self:has_bitmask_table() then
        print("Bitmask Table: " .. table_len(self.bitmask_table) .. " bitmasks")
    end

    -- Validation
    local errors = self:validate()
    if #errors > 0 then
        print(string.format("\nValidation Errors (%d):", #errors))
        for _, err in ipairs(errors) do
            print("  - " .. err)
        end
    else
        print("\nValidation passed")
    end

    print(sep)
end

