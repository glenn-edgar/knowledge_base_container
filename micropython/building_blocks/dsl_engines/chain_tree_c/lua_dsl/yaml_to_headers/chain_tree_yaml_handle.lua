    for _, kb_name in ipairs(kb_names) do
        print("\n--- Knowledge Base: " .. kb_name .. " ---")

        -- Get root and traverse
        local root = handle:get_kb_root_node(kb_name)
        print("Root node: " .. (root or "nil"))

        -- Show aliases
        local aliases = handle:get_kb_node_aliases(kb_name)
        if next(aliases) then
            local alias_strs = {}
            for alias, idx in pairs(aliases) do
                alias_strs[#alias_strs + 1] = alias .. "=" .. tostring(idx)
            end
            print("Node aliases: " .. table.concat(alias_strs, ", "))
        end

        -- Breadth-first traversal
        local bfs_order = handle:traverse_kb_breadth_first(kb_name)
        print(string.format("\nBreadth-first order (%d nodes):", #bfs_order))

        for i, ltree_name in ipairs(bfs_order) do
            local index = handle:get_node_index(ltree_name) or -1
            local label = handle:get_node_label(ltree_name) or "?"
            local node_name = handle:get_node_name(ltree_name) or "?"
            print(string.format("  [%2d] %-15s %-20s", index, label, node_name))

            -- Show functions for first few nodes
            if i <= 3 then
                local functions = handle:get_node_functions(ltree_name)
                if next(functions) then
                    local fn_strs = {}
                    for k, v in pairs(functions) do
                        fn_strs[#fn_strs + 1] = k .. "=" .. v
                    end
                    print("       Functions: " .. table.concat(fn_strs, ", "))
                end
                local children = handle:get_node_children(ltree_name)
                if #children > 0 then
                    print("       Children: " .. #children)
                end
            end
        end
    end

    -- Show event and bitmask tables
    if handle:has_event_table() then
        print("\n" .. sep)
        print("Event String Table")
        print(sep)
        local events = handle:get_event_string_table()
        local sorted_events = keys_sorted_by_value(events)
        for _, item in ipairs(sorted_events) do
            print(string.format("  [%d] %s", item.val, item.key))
        end
    end

    if handle:has_bitmask_table() then
        print("\n" .. sep)
        print("Bitmask Table")
        print(sep)
        local bitmasks = handle:get_bitmask_table()
        local sorted_bitmasks = keys_sorted_by_value(bitmasks)
        local bit = require("bit")
        for _, item in ipairs(sorted_bitmasks) do
            local mask_val = bit.lshift(1, item.val)
            print(string.format("  Bit %2d: %-20s = 0x%08X",
                item.val, item.key, mask_val))
        end
    end

    -- Show all functions
    print("\n" .. sep)
    print("All Functions")
    print(sep)
    local all_functions = handle:get_all_functions()

    print("\nMain Functions:")
    local main_keys = sorted_keys(all_functions.main)
    for _, fn in ipairs(main_keys) do
        print("  - " .. fn)
    end

    print("\nOne-Shot Functions:")
    local one_shot_keys = sorted_keys(all_functions.one_shot)
    for _, fn in ipairs(one_shot_keys) do
        print("  - " .. fn)
    end

    print("\nBoolean Functions:")
    local boolean_keys = sorted_keys(all_functions.boolean)
    for _, fn in ipairs(boolean_keys) do
        print("  - " .. fn)
    end

    print("\n" .. sep)
    print("Handle test completed successfully!")
end

return ChainTreeYamlHandle

