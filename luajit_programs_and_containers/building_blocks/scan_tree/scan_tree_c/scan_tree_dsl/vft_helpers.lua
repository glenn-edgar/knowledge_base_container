-- VFT_fuse: one-shot trip with clear cycle
--   output:        fuse blown status (1=blown, 0=intact)
--   input_param:   trip signal (1 bit)
--   clear_param:   clear signal (must cycle low->high->low to re-arm)
--   action_func:   C function name: void func(void *user_handle)
function M.VFT_fuse(dsl, output_param, input_param, clear_param, action_func)
    assert(type(action_func) == "string", "VFT_fuse: action_func must be a C function name string")
    local out_buf, out_start, out_count = dsl:validate_param(output_param, {require_bool = true})
    assert(out_count == 1, "VFT_fuse: output must be 1 bit")
    local in_buf, in_start, in_count = dsl:validate_param(input_param, {require_bool = true})
    assert(in_count == 1, "VFT_fuse: input must be 1 bit")
    local clr_buf, clr_start, clr_count = dsl:validate_param(clear_param, {require_bool = true})
    assert(clr_count == 1, "VFT_fuse: clear must be 1 bit")
    return {
        vft_name = "VFT_fuse", class = "system", lib_func = "st_vft_fuse",
        is_fuse = true,
        fuse_action = action_func,
        output = {buffer = out_buf.path, start = out_start, count = 1},
        inputs = {
            {buffer = in_buf.path, start = in_start, count = 1, role = M.ROLE_INPUT},
            {buffer = clr_buf.path, start = clr_start, count = 1, role = M.ROLE_CLEAR},
        },
    }
end

-- =================================================================
-- User VFT Factory
--
-- Usage:
--   local VFT_my_func = vft.user_vft("my_func", {
--       {name = "current",   type = "float", count = 1},
--       {name = "threshold", type = "float", count = 1},
--   })
--   dsl:instantiate_vft(VFT_my_func, "out:0-1", "buf_a:0-1", "buf_b:0-1")
-- =================================================================

function M.user_vft(func_name, input_specs)
    input_specs = input_specs or {}

    return function(dsl, output_param, ...)
        local args = {...}
        local out_buf, out_start, out_count = dsl:validate_param(output_param, {require_bool = true})
        assert(out_count == 1, string.format("user_vft_%s: output must be 1 bit", func_name))
        assert(#args == #input_specs,
            string.format("user_vft_%s: expected %d inputs, got %d", func_name, #input_specs, #args))

        local inputs = {}
        for i, spec in ipairs(input_specs) do
            local ib, is_, ic = dsl:validate_param(args[i])
            if spec.count and spec.count ~= "*" then
                assert(ic == spec.count,
                    string.format("user_vft_%s: input '%s' expected count %s, got %d",
                        func_name, spec.name, tostring(spec.count), ic))
            end
            inputs[#inputs + 1] = {
                buffer = ib.path, start = is_, count = ic,
                role = M.ROLE_DEFAULT, input_name = spec.name,
            }
        end

        return {
            vft_name = "VFT_user_" .. func_name,
            class = "user",
            user_func = "user_vft_" .. func_name,
            input_specs = input_specs,
            output = {buffer = out_buf.path, start = out_start, count = 1},
            inputs = inputs,
        }
    end
end

return M