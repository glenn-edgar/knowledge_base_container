--[[
    Scan Tree VFT Helpers v2

    Two VFT classes:
      system - implemented in scan_tree_lib, linked at compile time
      user   - prototypes generated by codegen, user implements

    JSON records include:
      class:    "system" | "user"
      lib_func: C function name (system) or nil
      user_func: C function name (user) or nil
      inputs[].role: integer role constant matching ST_ROLE_* in library
--]]

local M = {}

-- Role constants matching scan_tree_lib.h
M.ROLE_DEFAULT   = 0
M.ROLE_SET       = 1
M.ROLE_CLEAR     = 2
M.ROLE_THRESHOLD = 3
M.ROLE_BITS      = 4
M.ROLE_A         = 5
M.ROLE_B         = 6
M.ROLE_INPUT     = 7

-- =================================================================
-- System VFTs
-- =================================================================

function M.VFT_and(dsl, output_param, input_param)
    local out_buf, out_start, out_count = dsl:validate_param(output_param, {require_bool = true})
    assert(out_count == 1, "VFT_and: output must be 1 bit")
    local in_buf, in_start, in_count = dsl:validate_param(input_param, {require_bool = true})
    assert(in_count >= 1, "VFT_and: need >= 1 input bits")
    return {
        vft_name = "VFT_and", class = "system", lib_func = "st_vft_and",
        output = {buffer = out_buf.path, start = out_start, count = 1},
        inputs = {{buffer = in_buf.path, start = in_start, count = in_count, role = M.ROLE_DEFAULT}},
    }
end

