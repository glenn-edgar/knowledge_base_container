--[[
    hub_user_functions.lua -- Hub one-shot functions for test_robot.

    Each GENERATE_*_AVRC_PACKET function:
      1. Reads current_test_json from blackboard
      2. Decodes JSON to action table
      3. Generates an FFI command packet struct
      4. Writes a pointer to the packet into bb.command_packet

    The transport layer reads bb.command_packet and sends the binary
    packet to the remote. On real hardware, these packets go on the wire
    as-is — the FFI struct IS the wire format.

    DSL usage in hub_dsl.lua:
      ct:asm_one_shot_handler("GENERATE_INIT_CHECK_AVRC_PACKET",
          {"current_test_json", "command_packet"})
]]

local json_util = require("json_util")
local packets   = require("command_packets")

local M = {}
M.one_shot = {}

---------------------------------------------------------------------------
-- Helper: decode current_test_json, generate packet, write to bb
---------------------------------------------------------------------------
local function generate_packet(handle, node, generator)
    local bb = handle.blackboard
    local json_str = bb.current_test_json
    if not json_str or json_str == "" then return end

    local ok, action = pcall(json_util.decode, json_str)
    if not ok or not action then return end

    local pkt = generator(action)
    if pkt then
        bb.command_packet = pkt
    end
end

---------------------------------------------------------------------------
-- One-shot packet generators (one per KB type)
---------------------------------------------------------------------------

M.one_shot.GENERATE_INIT_CHECK_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_init_check)
end

M.one_shot.GENERATE_PATH_SPLINE_AVRC_PACKET = function(handle, node)
    local bb = handle.blackboard
    local json_str = bb.current_test_json
    if not json_str or json_str == "" then return end

    local ok, action = pcall(json_util.decode, json_str)
    if not ok or not action then return end

    -- Generate packet for first segment (subsequent segments
    -- are generated by the path KB's main loop as segments complete)
    local segments = action.segments
    if segments and #segments > 0 then
        bb.command_packet = packets.generate_path_segment(action, 1, segments[1])
        bb.path_segment_index = 1
        bb.path_total_segments = #segments
    end
end

M.one_shot.GENERATE_PATH_LINE_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, function(action)
        -- Line follow uses the same segment packet format
        local seg = {
            from = action.from, to = action.to,
            speed = action.speed, distance = action.distance,
        }
        return packets.generate_path_segment(action, 1, seg)
    end)
end

M.one_shot.GENERATE_PATH_WALL_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, function(action)
        local seg = {
            from = action.from, to = action.to,
            speed = action.speed, distance = action.distance,
        }
        return packets.generate_path_segment(action, 1, seg)
    end)
end

M.one_shot.GENERATE_PATH_ROTATE_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_rotate)
end

M.one_shot.GENERATE_DELIVER_PART_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_arm)
end

M.one_shot.GENERATE_PAINT_SAMPLE_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_arm)
end

M.one_shot.GENERATE_LOAD_SHIPPING_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_arm)
end

M.one_shot.GENERATE_PASS_GATE_AVRC_PACKET = function(handle, node)
    local bb = handle.blackboard
    local json_str = bb.current_test_json
    if not json_str or json_str == "" then return end

    local ok, action = pcall(json_util.decode, json_str)
    if not ok or not action then return end

    -- First command: open gate
    local params = action.params or action
    bb.command_packet = packets.generate_rpc_request(action, params.rpc_open or "gate.open")
end

M.one_shot.GENERATE_INSPECTION_SCAN_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_sensor_read)
end

M.one_shot.GENERATE_IDLE_AVRC_PACKET = function(handle, node)
    generate_packet(handle, node, packets.generate_idle)
end

---------------------------------------------------------------------------
-- Registry
---------------------------------------------------------------------------
M.registry = {
    one_shot = M.one_shot,
}

return M
