            f"#ifndef {guard}",
            f"#define {guard}",
            "",
            "#include <stdint.h>",
            "#include <stdbool.h>",
            "#include <string.h>",
            '#include "chaintree_support.h"',
            "",
            "/* Main function enum */",
            fb.main_indexer.generate_c_enum("MAIN_FUNC"),
            "",
            "/* One-shot function enum */",
            fb.one_shot_indexer.generate_c_enum("ONE_SHOT_FUNC"),
            "",
            "/* Boolean function enum */",
            fb.boolean_indexer.generate_c_enum("BOOL_FUNC"),
            "",
            f"extern const main_function_t {uid}_main_functions[{fb.main_indexer.get_count()}];",
            f"extern const one_shot_function_t {uid}_one_shot_functions[{fb.one_shot_indexer.get_count()}];",
            f"extern const boolean_function_t {uid}_boolean_functions[{fb.boolean_indexer.get_count()}];",
            "",
            f"extern const uint16_t {uid}_main_function_usage_count[{fb.main_indexer.get_count()}];",
