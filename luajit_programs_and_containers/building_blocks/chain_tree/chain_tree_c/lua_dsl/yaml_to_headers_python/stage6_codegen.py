"""
Stage 6: C Code Generator

Generates all .h and .c files from the built pipeline data:
  - chaintree_support.h/.c    (generic runtime)
  - {name}.h/.c               (instance handle)
  - {name}_nodes.h/.c         (node array)
  - {name}_functions.h/.c     (function tables)
  - {name}_links.h/.c         (link table)
  - {name}_node_data.h/.c     (JSON record data)
  - {name}_events.h/.c        (event string table)
  - {name}_bitmasks.h/.c      (bitmask definitions)
  - {name}_kb_info.h/.c       (knowledge base info)
"""

import struct
from pathlib import Path
from typing import Dict, List, Optional

from .stage1_handle import ChainTreeHandle
from .stage2_node_index import NodeIndexBuilder
from .stage3_function_index import FunctionIndexBuilder
from .stage4_link_table import LinkTableBuilder
from .stage5_node_data import NodeDataEncoder


class CCodeGenerator:
    """
    Generate all C header and implementation files from pipeline data.
    """
    
    def __init__(
        self,
        output_dir: Path,
        handle_name: str,
        unique_id: str,
        handle: ChainTreeHandle,
        node_builder: NodeIndexBuilder,
        function_builder: FunctionIndexBuilder,
        link_builder: LinkTableBuilder,
        data_encoder: Optional[NodeDataEncoder],
        main_function_usage: Dict[int, int],
        generate_support: bool = True,
    ):
        self.output_dir = output_dir
        self.handle_name = handle_name
        self.unique_id = unique_id
        self.handle = handle
        self.node_builder = node_builder
        self.function_builder = function_builder
        self.link_builder = link_builder
        self.data_encoder = data_encoder
        self.main_function_usage = main_function_usage
        self.generate_support = generate_support
    
    def _filter_executable_kbs(self, all_kb_names: List[str]) -> List[str]:
        """Filter out function mapping KBs that are not executable."""
        executable = []
        filtered = []
        for kb in all_kb_names:
            if kb.endswith('_test_functions') or kb == 'complete_functions_kb':
                filtered.append(kb)
            else:
                executable.append(kb)
        if filtered:
            print(f"\n  Note: Filtered out {len(filtered)} function mapping KB(s):")
            for kb in filtered:
                print(f"    - {kb}")
        return executable
    
    def _write(self, filename: str, lines: List[str]) -> None:
        """Write lines to a file in the output directory."""
        output_file = self.output_dir / filename
        with open(output_file, 'w') as f:
            f.write("\n".join(lines))
        print(f"  Generated: {output_file}")
    
    # =========================================================================
    # Public Entry Points
    # =========================================================================
    
    def generate_all(self) -> None:
        """Generate all header and implementation files."""
        self.generate_headers()
        self.generate_implementations()
    
    def generate_headers(self) -> None:
        if self.generate_support:
            self._gen_support_header()
        self._gen_instance_header()
        self._gen_node_struct_header()
        self._gen_function_headers()
        self._gen_link_table_header()
        if self.data_encoder:
            self._gen_node_data_header()
        self._gen_event_table_header()
        self._gen_bitmask_table_header()
        self._gen_kb_info_header()
    
    def generate_implementations(self) -> None:
        self._gen_handle_implementation()
        if self.generate_support:
            self._gen_support_implementation()
        self._gen_function_implementations()
        self._gen_node_array_implementation()
        self._gen_link_table_implementation()
        if self.data_encoder:
            self._gen_node_data_implementation()
        self._gen_event_table_implementation()
        self._gen_bitmask_table_implementation()
        self._gen_kb_info_implementation()
    
