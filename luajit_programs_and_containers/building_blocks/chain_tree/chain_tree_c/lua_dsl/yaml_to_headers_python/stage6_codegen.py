    def _gen_function_implementations(self) -> None:
        fb = self.function_builder
        uid = self.unique_id
        
        lines = [
            "/* Auto-generated by ChainTree Pipeline */",
            f'#include "{self.handle_name}_functions.h"',
            "",
            "/* Forward declarations - user must provide these functions */",
        ]
        
