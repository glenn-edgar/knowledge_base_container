    def _gen_kb_info_implementation(self) -> None:
        kb_names = self._filter_executable_kbs(self.handle.get_kb_names())
        uid = self.unique_id
        
        lines = [
            "/* Auto-generated by ChainTree Pipeline */",
            f'#include "{self.handle_name}_kb_info.h"',
            "",
        ]
        
        # Alias arrays
        kb_alias_info = {}
        for i, kb_name in enumerate(kb_names):
            aliases = self.handle.get_kb_node_aliases(kb_name)
            if aliases:
                lines.append(f"const node_alias_t {uid}_kb_{i}_aliases[{len(aliases)}] = {{")
                for alias_name, node_index in aliases.items():
                    lines.append(f'    {{"{alias_name}", {node_index}}},')
                lines.extend(["};", ""])
                kb_alias_info[i] = (True, len(aliases))
            else:
                kb_alias_info[i] = (False, 0)
        
        # KB table
        lines.append(f"const chaintree_kb_info_t {uid}_kb_table[{len(kb_names)}] = {{")
        
        for i, kb_name in enumerate(kb_names):
            start_idx, end_idx = self.node_builder.get_kb_range(kb_name)
            node_count = end_idx - start_idx
            root_node_index = start_idx
            
            max_depth = 0
            for idx in range(start_idx, end_idx):
                ltree_name = self.node_builder.final_index_to_ltree.get(idx)
                if ltree_name:
                    max_depth = max(max_depth, self.node_builder.get_node_depth(ltree_name))
            
            memory_factor = self.handle.get_kb_metadata(kb_name, "node_memory_factor", 10)
            
            has_aliases, alias_count = kb_alias_info[i]
            alias_ptr = f"{uid}_kb_{i}_aliases" if has_aliases else "NULL"
            
            lines.extend([
                "    {",
                f'        .kb_name = "{kb_name}",',
                f"        .root_node_index = {root_node_index},",
                f"        .start_index = {start_idx},",
                f"        .node_count = {node_count},",
                f"        .max_depth = {max_depth},",
                f"        .memory_factor = {memory_factor},",
                f"        .aliases = {alias_ptr},",
                f"        .alias_count = {alias_count}",
                "    },"
            ])
        
        lines.extend(["};", ""])
        self._write(f"{self.handle_name}_kb_info.c", lines)