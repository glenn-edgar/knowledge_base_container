#!/usr/bin/env python3
"""
generate_node_types.py

Generate C header with node type enum and mapping functions from YAML config.

Usage:
    python3 generate_node_types.py chaintree_types.yaml -o chaintree_node_types.h

The generated header contains:
    - ct_node_type_t enum
    - ct_type_from_string() function
    - ct_type_name() function
    - CT_TYPE_COUNT macro
"""

import argparse
import sys

try:
    import yaml
except ImportError:
    print("PyYAML not installed. Install with: pip install pyyaml")
    print("Or use JSON config file instead.")
    sys.exit(1)


def load_config(path: str) -> dict:
    """Load config from YAML or JSON file."""
    with open(path, 'r') as f:
        if path.endswith('.json'):
            import json
            return json.load(f)
        else:
            return yaml.safe_load(f)


def generate_header(config: dict, include_guard: str = None) -> str:
    """Generate C header from config."""
    
    types = config['types']
    default_type = config.get('default_type', 'CT_ACTION')
    enum_name = config.get('enum_name', 'ct_node_type_t')
    prefix = config.get('prefix', 'CT')
    
    if include_guard is None:
        include_guard = f"{prefix}_NODE_TYPES_H"
    
    lines = []
    
    # Header
    lines.append(f"#ifndef {include_guard}")
    lines.append(f"#define {include_guard}")
    lines.append("")
    lines.append("/* Auto-generated by generate_node_types.py */")
    lines.append("/* Do not edit - modify chaintree_types.yaml instead */")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("#include <string.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    
    # Enum definition
    lines.append("/**")
    lines.append(f" * {enum_name} - ChainTree node types")
    lines.append(" */")
    lines.append(f"typedef enum {{")
    
    for i, t in enumerate(types):
        desc = t.get('description', '')
        if desc:
            lines.append(f"    {t['enum_name']} = {i},  /* {desc} */")
        else:
            lines.append(f"    {t['enum_name']} = {i},")
    
    lines.append(f"    {prefix}_TYPE_COUNT")
    lines.append(f"}} {enum_name};")
    lines.append("")
    
    # No link constant
    lines.append(f"#define {prefix}_NO_LINK 0xFFFF")
    lines.append("")
    
    # String to enum function
    lines.append("/**")
    lines.append(f" * Convert JSON type string to {enum_name}.")
    lines.append(f" * Returns {default_type} for unknown types.")
    lines.append(" */")
    lines.append(f"static inline {enum_name} {prefix.lower()}_type_from_string(const char* s) {{")
    lines.append("    if (!s) return " + default_type + ";")
    lines.append("")
    
    for t in types:
        lines.append(f'    if (strcmp(s, "{t["json_name"]}") == 0) return {t["enum_name"]};')
    
    lines.append("")
    lines.append(f"    return {default_type};  /* default for unknown */")
    lines.append("}")
    lines.append("")
    
    # Enum to string function
    lines.append("/**")
    lines.append(f" * Convert {enum_name} to JSON type string.")
    lines.append(" */")
    lines.append(f"static inline const char* {prefix.lower()}_type_name({enum_name} type) {{")
    lines.append("    switch (type) {")
    
    for t in types:
        lines.append(f'        case {t["enum_name"]}: return "{t["json_name"]}";')
    
    lines.append('        default: return "unknown";')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    
    # Type info struct (optional - for runtime introspection)
    lines.append("/**")
    lines.append(" * Type information for runtime introspection.")
    lines.append(" */")
    lines.append(f"typedef struct {{")
    lines.append(f"    {enum_name} type;")
    lines.append("    const char* json_name;")
    lines.append("    const char* description;")
    lines.append(f"}} {prefix.lower()}_type_info_t;")
    lines.append("")
    
    lines.append(f"static const {prefix.lower()}_type_info_t {prefix.lower()}_type_info[{prefix}_TYPE_COUNT] = {{")
    for t in types:
        desc = t.get('description', '')
        lines.append(f'    {{ {t["enum_name"]}, "{t["json_name"]}", "{desc}" }},')
    lines.append("};")
    lines.append("")
    
    # C++ closing guard
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    
    # Footer
    lines.append(f"#endif /* {include_guard} */")
    
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description='Generate C header from node type YAML config.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Example:
    python3 generate_node_types.py chaintree_types.yaml -o chaintree_node_types.h
    
YAML format:
    types:
      - enum_name: CT_SEQUENCE
        json_name: sequence
        description: Run children in order
      - enum_name: CT_ACTION
        json_name: action
    default_type: CT_ACTION
    enum_name: ct_node_type_t
    prefix: CT
        """
    )
    parser.add_argument('config', help='YAML or JSON config file')
    parser.add_argument('-o', '--output', help='Output .h file (stdout if not specified)')
    parser.add_argument('--guard', help='Custom include guard name')
    
    args = parser.parse_args()
    
    config = load_config(args.config)
    header = generate_header(config, args.guard)
    
    if args.output:
        with open(args.output, 'w') as f:
            f.write(header)
        print(f"Generated: {args.output}")
        print(f"  {len(config['types'])} node types")
    else:
        print(header)


if __name__ == "__main__":
    main()