--[[
Header File Generator for ChainTree Binary

Generates:
  - *_bin.h     - Binary data as C array
  - *_hashes.h  - Hash definitions for functions/events/bitmasks
  - *_resolver.h - Template for user to implement function resolution
]]

local fnv1a = require("lib.fnv1a")

local M = {}

--------------------------------------------------------------------------------
-- Helper Functions
--------------------------------------------------------------------------------

local function upper_snake(name)
    -- Convert to UPPER_SNAKE_CASE
    return name:upper():gsub("[^%w]", "_")
end

local function safe_name(name)
    -- Make a C-safe identifier
    return name:gsub("[^%w_]", "_")
end

--------------------------------------------------------------------------------
-- Binary Header Generator (*_bin.h)
--------------------------------------------------------------------------------

function M.generate_bin_h(filepath, base_name, binary_data)
    local f = io.open(filepath, "w")
    if not f then
        error("Cannot create file: " .. filepath)
    end
    
    local guard = upper_snake(base_name) .. "_BIN_H"
    local array_name = base_name .. "_binary"
    
    f:write("/* Auto-generated by ChainTree Binary Generator */\n")
    f:write(string.format("#ifndef %s\n", guard))
    f:write(string.format("#define %s\n", guard))
    f:write("\n")
    f:write("#include <stdint.h>\n")
    f:write("\n")
    f:write(string.format("#define %s_SIZE %d\n", upper_snake(base_name), #binary_data))
    f:write("\n")
    f:write(string.format("const uint8_t %s[%d] = {\n", array_name, #binary_data))
    
    -- Write bytes in rows of 16
    local row_size = 16
    for i = 1, #binary_data, row_size do
        f:write("    ")
        for j = i, math.min(i + row_size - 1, #binary_data) do
            local byte = binary_data:byte(j)
            f:write(string.format("0x%02X", byte))
            if j < #binary_data then
                f:write(", ")
            end
        end
        f:write("\n")
    end
    
    f:write("};\n")
    f:write("\n")
    f:write(string.format("#endif /* %s */\n", guard))
    
    f:close()
end

--------------------------------------------------------------------------------
-- Hash Definitions Header (*_hashes.h)
--------------------------------------------------------------------------------

function M.generate_hashes_h(filepath, base_name, func_tables, events, bitmasks)
    local f = io.open(filepath, "w")
    if not f then
        error("Cannot create file: " .. filepath)
    end
    
    local guard = upper_snake(base_name) .. "_HASHES_H"
    
    f:write("/* Auto-generated by ChainTree Binary Generator */\n")
    f:write("/* Function and Event Hash Definitions */\n")
    f:write(string.format("#ifndef %s\n", guard))
    f:write(string.format("#define %s\n", guard))
    f:write("\n")
    f:write("#include <stdint.h>\n")
    f:write("\n")
    
    -- CFL_NULL special hash
    f:write("/* Special null function hash */\n")
    f:write("#define HASH_CFL_NULL 0x00000000\n")
    f:write("\n")
    
    -- Main function hashes
    f:write("/* ========== Main Function Hashes ========== */\n")
    for _, func in ipairs(func_tables.main) do
        if func.name ~= "CFL_NULL" then
            local macro_name = "HASH_MAIN_" .. upper_snake(func.name)
            f:write(string.format("#define %-50s 0x%08X\n", macro_name, func.hash))
        end
    end
    f:write("\n")
    
    -- One-shot function hashes
    f:write("/* ========== One-Shot Function Hashes ========== */\n")
    for _, func in ipairs(func_tables.one_shot) do
        if func.name ~= "CFL_NULL" then
            local macro_name = "HASH_ONE_SHOT_" .. upper_snake(func.name)
            f:write(string.format("#define %-50s 0x%08X\n", macro_name, func.hash))
        end
    end
    f:write("\n")
    
    -- Boolean function hashes
    f:write("/* ========== Boolean Function Hashes ========== */\n")
    for _, func in ipairs(func_tables.boolean) do
        if func.name ~= "CFL_NULL" then
            local macro_name = "HASH_BOOLEAN_" .. upper_snake(func.name)
            f:write(string.format("#define %-50s 0x%08X\n", macro_name, func.hash))
        end
    end
    f:write("\n")
    
    -- Event hashes
    if #events > 0 then
        f:write("/* ========== Event Hashes ========== */\n")
        for _, event in ipairs(events) do
            local macro_name = "HASH_EVENT_" .. upper_snake(event.name)
            f:write(string.format("#define %-50s 0x%08X  /* index=%d */\n", 
                macro_name, event.hash, event.index))
        end
        f:write("\n")
    end
    
    -- Bitmask hashes
    if #bitmasks > 0 then
        f:write("/* ========== Bitmask Hashes ========== */\n")
        for _, bitmask in ipairs(bitmasks) do
            local macro_name = "HASH_BITMASK_" .. upper_snake(bitmask.name)
            f:write(string.format("#define %-50s 0x%08X  /* bit=%d */\n", 
                macro_name, bitmask.hash, bitmask.bit))
        end
        f:write("\n")
    end
    
    -- Function counts
    f:write("/* ========== Counts ========== */\n")
    f:write(string.format("#define %s_MAIN_FUNCTION_COUNT      %d\n", 
        upper_snake(base_name), #func_tables.main))
    f:write(string.format("#define %s_ONE_SHOT_FUNCTION_COUNT  %d\n", 
        upper_snake(base_name), #func_tables.one_shot))
    f:write(string.format("#define %s_BOOLEAN_FUNCTION_COUNT   %d\n", 
        upper_snake(base_name), #func_tables.boolean))
    f:write(string.format("#define %s_EVENT_COUNT              %d\n", 
        upper_snake(base_name), #events))
    f:write(string.format("#define %s_BITMASK_COUNT            %d\n", 
        upper_snake(base_name), #bitmasks))
    f:write("\n")
    
    f:write(string.format("#endif /* %s */\n", guard))
    
    f:close()
end

--------------------------------------------------------------------------------
-- Resolver Template Header (*_resolver.h)
--------------------------------------------------------------------------------

function M.generate_resolver_h(filepath, base_name, func_tables)
    local f = io.open(filepath, "w")
    if not f then
        error("Cannot create file: " .. filepath)
    end
    
    local guard = upper_snake(base_name) .. "_RESOLVER_H"
    
    f:write("/* Auto-generated by ChainTree Binary Generator */\n")
    f:write("/* User must implement these resolver functions */\n")
    f:write(string.format("#ifndef %s\n", guard))
    f:write(string.format("#define %s\n", guard))
    f:write("\n")
    f:write("#include <stdint.h>\n")
    f:write("#include <stdbool.h>\n")
    f:write("#include \"chaintree_binary_support.h\"\n")
    f:write(string.format("#include \"%s_hashes.h\"\n", base_name))
    f:write("\n")
    
    -- Function pointer types (for reference)
    f:write("/* Function pointer types (from chaintree_binary_support.h) */\n")
    f:write("/*\n")
    f:write(" * typedef unsigned (*main_function_t)(void *handle, unsigned bool_function_index,\n")
    f:write(" *     unsigned node_index, unsigned event_type, unsigned event_id, void *event_data);\n")
    f:write(" * typedef void (*one_shot_function_t)(void *handle, unsigned node_index);\n")
    f:write(" * typedef bool (*boolean_function_t)(void *handle, unsigned node_index,\n")
    f:write(" *     unsigned event_type, unsigned event_id, void *event_data);\n")
    f:write(" */\n")
    f:write("\n")
    
    -- Resolver function declarations
    f:write("/* ========== Resolver Function Declarations ========== */\n")
    f:write("\n")
    f:write("/*\n")
    f:write(" * Resolve main function hash to function pointer.\n")
    f:write(" * Called during binary loading for each unique main function.\n")
    f:write(" * Return NULL if hash not recognized (will cause load failure).\n")
    f:write(" */\n")
    f:write("main_function_t resolve_main_function(uint32_t hash);\n")
    f:write("\n")
    f:write("/*\n")
    f:write(" * Resolve one-shot function hash to function pointer.\n")
    f:write(" */\n")
    f:write("one_shot_function_t resolve_one_shot_function(uint32_t hash);\n")
    f:write("\n")
    f:write("/*\n")
    f:write(" * Resolve boolean function hash to function pointer.\n")
    f:write(" */\n")
    f:write("boolean_function_t resolve_boolean_function(uint32_t hash);\n")
    f:write("\n")
    
    -- Example implementation in comments
    f:write("/* ========== Example Implementation ========== */\n")
    f:write("/*\n")
    f:write(" * // Forward declarations for your function implementations\n")
    
    -- List main functions
    for _, func in ipairs(func_tables.main) do
        local fn_name = string.lower(func.name) .. "_main_fn"
        f:write(string.format(" * extern unsigned %s(void *handle, unsigned bool_function_index,\n", fn_name))
        f:write(" *     unsigned node_index, unsigned event_type, unsigned event_id, void *event_data);\n")
    end
    f:write(" *\n")
    
    -- Example resolver switch
    f:write(" * main_function_t resolve_main_function(uint32_t hash) {\n")
    f:write(" *     switch (hash) {\n")
    for _, func in ipairs(func_tables.main) do
        local macro_name
        if func.name == "CFL_NULL" then
            macro_name = "HASH_CFL_NULL"
        else
            macro_name = "HASH_MAIN_" .. upper_snake(func.name)
        end
        local fn_name = string.lower(func.name) .. "_main_fn"
        f:write(string.format(" *         case %s: return %s;\n", macro_name, fn_name))
    end
    f:write(" *         default: return NULL;\n")
    f:write(" *     }\n")
    f:write(" * }\n")
    f:write(" */\n")
    f:write("\n")
    
    f:write(string.format("#endif /* %s */\n", guard))
    
    f:close()
end

--------------------------------------------------------------------------------
-- Binary Support Header (runtime loading support)
--------------------------------------------------------------------------------

function M.generate_binary_support_h(filepath)
    local f = io.open(filepath, "w")
    if not f then
        error("Cannot create file: " .. filepath)
    end
    
    f:write([[/* ChainTree Binary Support Header */
#ifndef CHAINTREE_BINARY_SUPPORT_H
#define CHAINTREE_BINARY_SUPPORT_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* ===== Binary Header Structure ===== */
typedef struct __attribute__((packed)) {
    uint8_t  magic[4];              /* "CTRB" */
    uint16_t version;               /* 0x0001 */
    uint16_t flags;                 /* Reserved */
    uint32_t total_size;            /* Total binary size including CRCs */
    
    /* Section offsets from binary start */
    uint32_t nodes_offset;
    uint32_t link_table_offset;
    uint32_t kb_table_offset;
    uint32_t kb_aliases_offset;
    uint32_t main_func_hashes_offset;
    uint32_t one_shot_func_hashes_offset;
    uint32_t boolean_func_hashes_offset;
    uint32_t main_func_usage_offset;
    uint32_t event_hashes_offset;
    uint32_t bitmask_hashes_offset;
    uint32_t node_data_records_offset;
    uint32_t node_data_controls_offset;
    uint32_t node_data_strings_offset;
    
    /* Counts */
    uint16_t node_count;
    uint16_t link_table_size;
    uint16_t kb_count;
    uint16_t main_function_count;
    uint16_t one_shot_function_count;
    uint16_t boolean_function_count;
    uint16_t event_count;
    uint16_t bitmask_count;
    uint16_t node_data_records_count;
    uint16_t node_data_controls_count;
    uint16_t node_data_strings_size;
    uint16_t total_aliases_count;
    
    uint32_t unique_id_hash;
    uint32_t header_hash;
} chaintree_binary_header_t;

/* ===== Binary Node Structure ===== */
typedef struct __attribute__((packed)) {
    uint16_t node_index;
    uint16_t parent_index;
    uint16_t depth;
    uint16_t link_start;
    uint16_t link_count;            /* Bits 0-14: count, Bit 15: auto_start */
    uint16_t main_function_index;
    uint16_t init_function_index;
    uint16_t aux_function_index;
    uint16_t term_function_index;
    uint16_t node_data_id;
} chaintree_binary_node_t;

/* ===== Binary KB Info Structure ===== */
typedef struct __attribute__((packed)) {
    uint32_t kb_name_hash;
    uint16_t root_node_index;
    uint16_t start_index;
    uint16_t node_count;
    uint16_t max_depth;
    uint16_t memory_factor;
    uint16_t alias_count;
    uint32_t aliases_offset;        /* Index into aliases array */
} chaintree_binary_kb_info_t;

/* ===== Binary Alias Structure ===== */
typedef struct __attribute__((packed)) {
    uint32_t alias_hash;
    uint16_t node_index;
    uint16_t padding;
} chaintree_binary_alias_t;

/* ===== Function Pointer Types ===== */
typedef unsigned (*main_function_t)(void *handle, unsigned bool_function_index,
    unsigned node_index, unsigned event_type, unsigned event_id, void *event_data);
typedef void (*one_shot_function_t)(void *handle, unsigned node_index);
typedef bool (*boolean_function_t)(void *handle, unsigned node_index,
    unsigned event_type, unsigned event_id, void *event_data);

/* ===== Allocator Interface ===== */
typedef void* (*ct_alloc_fn)(void *alloc_handle, size_t size);
typedef void  (*ct_free_fn)(void *alloc_handle, void *ptr);

typedef struct {
    void *handle;
    ct_alloc_fn alloc;
    ct_free_fn free;
} ct_allocator_t;

/* ===== Function Resolvers ===== */
typedef main_function_t     (*ct_resolve_main_fn)(uint32_t hash);
typedef one_shot_function_t (*ct_resolve_one_shot_fn)(uint32_t hash);
typedef boolean_function_t  (*ct_resolve_boolean_fn)(uint32_t hash);

typedef struct {
    ct_resolve_main_fn     resolve_main;
    ct_resolve_one_shot_fn resolve_one_shot;
    ct_resolve_boolean_fn  resolve_boolean;
} ct_resolver_t;

/* ===== Runtime Handle (created by loader) ===== */
typedef struct {
    /* Binary data (can be in flash) */
    const uint8_t *binary_base;
    const chaintree_binary_header_t *header;
    
    /* Resolved function tables (allocated by loader) */
    main_function_t *main_functions;
    one_shot_function_t *one_shot_functions;
    boolean_function_t *boolean_functions;
    
    /* Quick access pointers (into binary) */
    const chaintree_binary_node_t *nodes;
    const uint16_t *link_table;
    const chaintree_binary_kb_info_t *kb_table;
    const chaintree_binary_alias_t *aliases;
    const uint16_t *main_func_usage;
    const uint32_t *event_hashes;
    const uint32_t *bitmask_hashes;
} chaintree_runtime_t;

/* ===== Load Result Codes ===== */
typedef enum {
    CT_LOAD_OK = 0,
    CT_LOAD_ERR_NULL_INPUT,
    CT_LOAD_ERR_MAGIC,
    CT_LOAD_ERR_VERSION,
    CT_LOAD_ERR_SIZE,
    CT_LOAD_ERR_HEADER_CRC,
    CT_LOAD_ERR_DATA_CRC,
    CT_LOAD_ERR_ALLOC,
    CT_LOAD_ERR_RESOLVE_MAIN,
    CT_LOAD_ERR_RESOLVE_ONE_SHOT,
    CT_LOAD_ERR_RESOLVE_BOOLEAN,
} ct_load_result_t;

/* ===== API Functions ===== */

/*
 * Load binary and create runtime handle.
 */
ct_load_result_t ct_load_binary(
    const uint8_t *binary_data,
    uint32_t binary_size,
    const ct_allocator_t *allocator,
    const ct_resolver_t *resolver,
    chaintree_runtime_t **runtime_out
);

/*
 * Unload and free all resources.
 */
void ct_unload(
    chaintree_runtime_t *runtime,
    const ct_allocator_t *allocator
);

/*
 * Verify binary integrity without loading.
 */
ct_load_result_t ct_verify_binary(
    const uint8_t *binary_data,
    uint32_t binary_size
);

/*
 * Get unique_id hash from binary without full load.
 */
uint32_t ct_get_binary_id_hash(const uint8_t *binary_data);

/*
 * FNV-1a hash utility.
 */
uint32_t ct_fnv1a_hash(const char *str);

/* ===== Accessor Macros ===== */
#define CT_GET_NODE(rt, idx) (&(rt)->nodes[idx])
#define CT_GET_LINK(rt, idx) ((rt)->link_table[idx])
#define CT_GET_KB(rt, idx) (&(rt)->kb_table[idx])

#define CT_NODE_LINK_COUNT(node) ((node)->link_count & 0x7FFF)
#define CT_NODE_AUTO_START(node) (((node)->link_count & 0x8000) != 0)

#endif /* CHAINTREE_BINARY_SUPPORT_H */
]])
    
    f:close()
end

return M