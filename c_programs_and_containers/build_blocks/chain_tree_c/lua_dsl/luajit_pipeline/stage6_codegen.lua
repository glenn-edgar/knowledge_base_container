function CCodeGenerator:_gen_node_array_implementation()
    local uid = self.unique_id
    local array_size = self.node_builder:get_array_size()

    local lines = {
        "/* Auto-generated by ChainTree Pipeline (LuaJIT) */",
        string.format('#include "%s_nodes.h"', self.handle_name),
        "",
        "/* Node array - preserves original indices; filtered nodes leave gaps */",
        string.format("const chaintree_node_t %s_nodes[%d] = {", uid, array_size),
    }

    for i = 0, array_size - 1 do
        local ltree_name = self.node_builder:get_node_by_index(i)

        if not ltree_name then
            lines[#lines + 1] = string.format("    /* [%d] FILTERED */ {", i)
            lines[#lines + 1] = string.format("        .node_index = %d, .parent_index = 0xFFFF, .depth = 0,", i)
            lines[#lines + 1] = "        .link_start = 0, .link_count = 0,"
            lines[#lines + 1] = "        .main_function_index = 0, .init_function_index = 0,"
            lines[#lines + 1] = "        .aux_function_index = 0, .term_function_index = 0,"
            lines[#lines + 1] = "        .node_data_id = 0xFFFF"
            lines[#lines + 1] = "    },"
        else
            local node_data = self.handle:get_node_data(ltree_name)
            if not node_data then
                lines[#lines + 1] = string.format("    /* [%d] ERROR: not found: %s */", i, ltree_name)
            else
                local functions = self.handle:get_node_functions(ltree_name)
                local main_idx = self.function_builder.main_indexer:get_index(functions.main)
                local init_idx = self.function_builder.one_shot_indexer:get_index(functions.init)
                local aux_idx = self.function_builder.boolean_indexer:get_index(functions.aux)
                local term_idx = self.function_builder.one_shot_indexer:get_index(functions.term)

                local link_info = self.link_builder:get_node_link_info(ltree_name)
                local link_start = link_info.link_start
                local link_count = link_info.link_count

                local node_dict = node_data.node_dict or {}
                local auto_start = false
                if type(node_dict) == "table" then
                    auto_start = node_dict.auto_start and true or false
                end

                local packed = bit.band(link_count, 0x7FFF)
                if auto_start then packed = bit.bor(packed, 0x8000) end

                local parent_ltree = self.handle:get_node_parent(ltree_name)
                local parent_idx = 0xFFFF
                if parent_ltree and self.node_builder.ltree_to_final_index[parent_ltree] then
                    parent_idx = self.node_builder:get_node_final_index(parent_ltree)
                end

                local depth = self.node_builder:get_node_depth(ltree_name)
                local data_id = 0xFFFF
                if self.data_encoder then
                    data_id = self.data_encoder:get_node_data_id(ltree_name)
                end

                local node_name = node_data.node_name or "unknown"
                local auto_tag = auto_start and " [AUTO_START]" or ""

                lines[#lines + 1] = string.format("    /* [%d] %s%s */", i, node_name, auto_tag)
                lines[#lines + 1] = "    {"
                lines[#lines + 1] = string.format("        .node_index = %d,", i)
                lines[#lines + 1] = string.format("        .parent_index = %d,", parent_idx)
                lines[#lines + 1] = string.format("        .depth = %d,", depth)
                lines[#lines + 1] = string.format("        .link_start = %d,", link_start)
                lines[#lines + 1] = string.format("        .link_count = 0x%04X,  /* count=%d, auto_start=%s */", packed, link_count, tostring(auto_start))
                lines[#lines + 1] = string.format("        .main_function_index = %d,", main_idx)
                lines[#lines + 1] = string.format("        .init_function_index = %d,", init_idx)
                lines[#lines + 1] = string.format("        .aux_function_index = %d,", aux_idx)
                lines[#lines + 1] = string.format("        .term_function_index = %d,", term_idx)
                lines[#lines + 1] = string.format("        .node_data_id = %d", data_id)
                lines[#lines + 1] = "    },"
            end
        end
    end

    lines[#lines + 1] = "};"
    lines[#lines + 1] = ""
    self:_write(self.handle_name .. "_nodes.c", lines)
end

