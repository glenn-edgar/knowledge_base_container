function CCodeGenerator:_gen_support_implementation()
    local lines = {
        '/* Auto-generated by ChainTree Pipeline (LuaJIT) - Generic Support Functions */',
        '#include "chaintree_support.h"',
        '#include <string.h>',
        "",
    }

    local func_types = {
        { "main_function",    "main_function_count",    "main_function_names"    },
        { "one_shot_function","one_shot_function_count", "one_shot_function_names" },
        { "boolean_function", "boolean_function_count",  "boolean_function_names"  },
    }

    for _, ft in ipairs(func_types) do
        local label, count_field, names_field = ft[1], ft[2], ft[3]
        -- get name by index
        lines[#lines + 1] = string.format("const char* ct_get_%s_name(const chaintree_handle_t *handle, uint16_t func_index) {", label)
        lines[#lines + 1] = string.format("    if (handle == NULL || handle->%s == NULL) return NULL;", names_field)
        lines[#lines + 1] = string.format("    if (func_index >= handle->%s) return NULL;", count_field)
        lines[#lines + 1] = string.format("    return handle->%s[func_index];", names_field)
        lines[#lines + 1] = "}"
        lines[#lines + 1] = ""
        -- get index by name
        lines[#lines + 1] = string.format("int ct_get_%s_index(const chaintree_handle_t *handle, const char *func_name) {", label)
        lines[#lines + 1] = string.format("    if (handle == NULL || func_name == NULL || handle->%s == NULL) return -1;", names_field)
        lines[#lines + 1] = string.format("    for (uint16_t i = 0; i < handle->%s; i++) {", count_field)
        lines[#lines + 1] = string.format("        if (strcmp(func_name, handle->%s[i]) == 0) return i;", names_field)
        lines[#lines + 1] = "    }"
        lines[#lines + 1] = "    return -1;"
        lines[#lines + 1] = "}"
        lines[#lines + 1] = ""
    end

    -- Event lookups
    for _, line in ipairs({
        "const char* ct_get_event_name(const chaintree_handle_t *handle, uint16_t event_index) {",
        "    if (handle == NULL || handle->event_strings == NULL) return NULL;",
        "    if (event_index >= handle->event_count) return NULL;",
        "    return handle->event_strings[event_index];",
        "}",
        "",
        "int ct_get_event_index(const chaintree_handle_t *handle, const char *name) {",
        "    if (handle == NULL || name == NULL || handle->event_strings == NULL) return -1;",
        "    for (uint16_t i = 0; i < handle->event_count; i++) {",
        "        if (strcmp(name, handle->event_strings[i]) == 0) return i;",
        "    }",
        "    return -1;",
        "}",
        "",
        "const char* ct_get_bitmask_name(const chaintree_handle_t *handle, uint8_t bit_index) {",
        "    if (handle == NULL || handle->bitmask_names == NULL) return NULL;",
        "    if (bit_index >= handle->bitmask_count) return NULL;",
        "    return handle->bitmask_names[bit_index];",
        "}",
        "",
        "int ct_get_bitmask_index(const chaintree_handle_t *handle, const char *name) {",
        "    if (handle == NULL || name == NULL || handle->bitmask_names == NULL) return -1;",
        "    for (uint8_t i = 0; i < handle->bitmask_count; i++) {",
        "        if (strcmp(name, handle->bitmask_names[i]) == 0) return i;",
        "    }",
        "    return -1;",
        "}",
        "",
        "uint16_t ct_get_kb_count(const chaintree_handle_t *handle) {",
        "    if (handle == NULL) return 0;",
        "    return handle->kb_count;",
        "}",
        ""
    }) do
        lines[#lines + 1] = line
    end

    self:_write("chaintree_support.c", lines)
end

