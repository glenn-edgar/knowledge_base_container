function CCodeGenerator:_gen_kb_info_implementation()
    local kb_names = self:_filter_executable_kbs(self.handle:get_kb_names())
    local uid = self.unique_id

    local lines = {
        "/* Auto-generated by ChainTree Pipeline (LuaJIT) */",
        string.format('#include "%s_kb_info.h"', self.handle_name),
        "",
    }

    -- Alias arrays
    local kb_alias_info = {}
    for i, kb_name in ipairs(kb_names) do
        local idx = i - 1
        local aliases = self.handle:get_kb_node_aliases(kb_name)
        local alias_count = table_len(aliases)
        if alias_count > 0 then
            lines[#lines + 1] = string.format("const node_alias_t %s_kb_%d_aliases[%d] = {", uid, idx, alias_count)
            for alias_name, node_index in sorted_pairs_by_key(aliases) do
                lines[#lines + 1] = string.format('    {"%s", %d},', alias_name, node_index)
            end
            lines[#lines + 1] = "};"
            lines[#lines + 1] = ""
            kb_alias_info[idx] = { true, alias_count }
        else
            kb_alias_info[idx] = { false, 0 }
        end
    end

    -- KB table
    lines[#lines + 1] = string.format("const chaintree_kb_info_t %s_kb_table[%d] = {", uid, #kb_names)

    for i, kb_name in ipairs(kb_names) do
        local idx = i - 1
        local start_idx, end_idx = self.node_builder:get_kb_range(kb_name)
        local node_count = end_idx - start_idx
        local root_node_index = start_idx

        local max_depth = 0
        for j = start_idx, end_idx - 1 do
            local ltree_name = self.node_builder:get_node_by_index(j)
            if ltree_name then
                local d = self.node_builder:get_node_depth(ltree_name)
                if d > max_depth then max_depth = d end
            end
        end

        local memory_factor = self.handle:get_kb_metadata_value(kb_name, "node_memory_factor", 10)

        local info = kb_alias_info[idx]
        local alias_ptr = info[1] and string.format("%s_kb_%d_aliases", uid, idx) or "NULL"
        local alias_count = info[2]

        lines[#lines + 1] = "    {"
        lines[#lines + 1] = string.format('        .kb_name = "%s",', kb_name)
        lines[#lines + 1] = string.format("        .root_node_index = %d,", root_node_index)
        lines[#lines + 1] = string.format("        .start_index = %d,", start_idx)
        lines[#lines + 1] = string.format("        .node_count = %d,", node_count)
        lines[#lines + 1] = string.format("        .max_depth = %d,", max_depth)
        lines[#lines + 1] = string.format("        .memory_factor = %d,", memory_factor)
        lines[#lines + 1] = string.format("        .aliases = %s,", alias_ptr)
        lines[#lines + 1] = string.format("        .alias_count = %d", alias_count)
        lines[#lines + 1] = "    },"
    end

    lines[#lines + 1] = "};"
    lines[#lines + 1] = ""
    self:_write(self.handle_name .. "_kb_info.c", lines)
end

