function CCodeGenerator:_gen_instance_header()
    local guard = self.handle_name:upper() .. "_H"
    local lines = {
        "/* Auto-generated by ChainTree Pipeline (LuaJIT) */",
        "#ifndef " .. guard,
        "#define " .. guard,
        "",
        '#include "chaintree_support.h"',
        string.format('#include "%s_nodes.h"', self.handle_name),
        string.format('#include "%s_links.h"', self.handle_name),
        string.format('#include "%s_events.h"', self.handle_name),
        string.format('#include "%s_bitmasks.h"', self.handle_name),
        string.format('#include "%s_kb_info.h"', self.handle_name),
        string.format('#include "%s_node_data.h"', self.handle_name),
        string.format('#include "%s_functions.h"', self.handle_name),
        "",
        string.format("extern const chaintree_handle_t g_%s;", self.handle_name),
        "",
        "#endif /* " .. guard .. " */"
    }
    self:_write(self.handle_name .. ".h", lines)
end

function CCodeGenerator:_gen_handle_implementation()
    local uid = self.unique_id
    local fb = self.function_builder
    local records_count = self.data_encoder and self.data_encoder:get_records_count() or 0
    local strings_size = self.data_encoder and self.data_encoder:get_strings_size() or 0
    local controls_count = self.data_encoder and self.data_encoder:get_controls_count() or 0

    local kb_names = self:_filter_executable_kbs(self.handle:get_kb_names())
    local event_count = table_len(self.handle:get_event_string_table())
    local bitmask_count = table_len(self.handle:get_bitmask_table())

    local lines = {
        "/* Auto-generated by ChainTree Pipeline (LuaJIT) */",
        "",
        string.format('#include "%s.h"', self.handle_name),
        "",
        string.format("const chaintree_handle_t g_%s = {", self.handle_name),
        string.format('    .unique_id = "%s",', uid),
        "",
        string.format("    .nodes = %s_nodes,", uid),
        string.format("    .node_count = %d,", self.node_builder:get_total_nodes()),
        "",
        string.format("    .main_functions = %s_main_functions,", uid),
        string.format("    .main_function_count = %d,", fb.main_indexer:get_count()),
        string.format("    .one_shot_functions = %s_one_shot_functions,", uid),
        string.format("    .one_shot_function_count = %d,", fb.one_shot_indexer:get_count()),
        string.format("    .boolean_functions = %s_boolean_functions,", uid),
        string.format("    .boolean_function_count = %d,", fb.boolean_indexer:get_count()),
        "",
        string.format("    .main_function_names = %s_main_function_names,", uid),
        string.format("    .one_shot_function_names = %s_one_shot_function_names,", uid),
        string.format("    .boolean_function_names = %s_boolean_function_names,", uid),
        "",
        string.format("    .main_function_usage_count = %s_main_function_usage_count,", uid),
        "",
        string.format("    .link_table = %s_link_table,", uid),
        string.format("    .link_table_size = %d,", self.link_builder:get_link_table_size()),
        "",
        string.format("    .event_strings = (const char **)%s_event_strings,", uid),
        string.format("    .event_count = %d,", event_count),
        "",
        string.format("    .bitmask_names = (const char **)%s_bitmask_names,", uid),
        string.format("    .bitmask_count = %d,", bitmask_count),
        "",
        string.format("    .kb_table = %s_kb_table,", uid),
        string.format("    .kb_count = %d,", #kb_names),
        "",
    }

    if self.data_encoder and records_count > 0 then
        lines[#lines + 1] = string.format("    .node_data_records = %s_node_data_records,", uid)
        lines[#lines + 1] = string.format("    .node_data_records_count = %d,", records_count)
        lines[#lines + 1] = string.format("    .node_data_strings = %s_node_data_strings,", uid)
        lines[#lines + 1] = string.format("    .node_data_strings_size = %d,", strings_size)
        lines[#lines + 1] = string.format("    .node_data_controls = %s_node_data_controls,", uid)
        lines[#lines + 1] = string.format("    .node_data_controls_count = %d", controls_count)
    else
        lines[#lines + 1] = "    .node_data_records = NULL,"
        lines[#lines + 1] = "    .node_data_records_count = 0,"
        lines[#lines + 1] = "    .node_data_strings = NULL,"
        lines[#lines + 1] = "    .node_data_strings_size = 0,"
        lines[#lines + 1] = "    .node_data_controls = NULL,"
        lines[#lines + 1] = "    .node_data_controls_count = 0"
    end

    lines[#lines + 1] = "};"
    lines[#lines + 1] = ""
    self:_write(self.handle_name .. ".c", lines)
end

