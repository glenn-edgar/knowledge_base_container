--[[
  stage6_codegen.lua - Generate all .h and .c files from pipeline data.
  LuaJIT port of stage6_codegen.py
  
  Generates 9 matched pairs:
    - chaintree_support.h/.c    (generic runtime)
    - {name}.h/.c               (instance handle)
    - {name}_nodes.h/.c         (node array)
    - {name}_functions.h/.c     (function tables)
    - {name}_links.h/.c         (link table)
    - {name}_node_data.h/.c     (JSON record data)
    - {name}_events.h/.c        (event string table)
    - {name}_bitmasks.h/.c      (bitmask definitions)
    - {name}_kb_info.h/.c       (knowledge base info)
--]]

local CCodeGenerator = {}
CCodeGenerator.__index = CCodeGenerator

function CCodeGenerator.new(opts)
    local self = setmetatable({}, CCodeGenerator)
    self.output_dir = opts.output_dir
    self.handle_name = opts.handle_name
    self.unique_id = opts.unique_id
    self.handle = opts.handle
    self.node_builder = opts.node_builder
    self.function_builder = opts.function_builder
    self.link_builder = opts.link_builder
    self.data_encoder = opts.data_encoder       -- may be nil
    self.main_function_usage = opts.main_function_usage
    self.generate_support = opts.generate_support
    return self
end

-- =========================================================================
-- Helpers
-- =========================================================================

local function sorted_pairs_by_value(tbl)
    local items = {}
    for k, v in pairs(tbl) do items[#items + 1] = { k, v } end
    table.sort(items, function(a, b) return a[2] < b[2] end)
    local i = 0
    return function()
        i = i + 1
        if items[i] then return items[i][1], items[i][2] end
    end
end

local function sorted_pairs_by_key(tbl)
    local items = {}
    for k, v in pairs(tbl) do items[#items + 1] = { k, v } end
    table.sort(items, function(a, b) return tostring(a[1]) < tostring(b[1]) end)
    local i = 0
    return function()
        i = i + 1
        if items[i] then return items[i][1], items[i][2] end
    end
end

local function safe_name(s)
    return s:upper():gsub(" ", "_"):gsub("-", "_")
end

local function table_len(t)
    local n = 0
    for _ in pairs(t) do n = n + 1 end
    return n
end

function CCodeGenerator:_filter_executable_kbs(all_kb_names)
    local executable = {}
    local filtered = {}
    for _, kb in ipairs(all_kb_names) do
        if kb:match("_test_functions$") or kb == "complete_functions_kb" then
            filtered[#filtered + 1] = kb
        else
            executable[#executable + 1] = kb
        end
    end
    if #filtered > 0 then
        print(string.format("\n  Note: Filtered out %d function mapping KB(s):", #filtered))
        for _, kb in ipairs(filtered) do
            print("    - " .. kb)
        end
    end
    return executable
end

function CCodeGenerator:_write(filename, lines)
    local path = self.output_dir .. "/" .. filename
    local f = io.open(path, "w")
    if not f then error("Cannot open for writing: " .. path) end
    f:write(table.concat(lines, "\n"))
    f:close()
    print("  Generated: " .. path)
end

-- =========================================================================
-- Public Entry Points
-- =========================================================================

function CCodeGenerator:generate_all()
    self:generate_headers()
    self:generate_implementations()
end

function CCodeGenerator:generate_headers()
    if self.generate_support then self:_gen_support_header() end
    self:_gen_instance_header()
    self:_gen_node_struct_header()
    self:_gen_function_headers()
    self:_gen_link_table_header()
    if self.data_encoder then self:_gen_node_data_header() end
    self:_gen_event_table_header()
    self:_gen_bitmask_table_header()
    self:_gen_kb_info_header()
end

function CCodeGenerator:generate_implementations()
    self:_gen_handle_implementation()
    if self.generate_support then self:_gen_support_implementation() end
    self:_gen_function_implementations()
    self:_gen_node_array_implementation()
    self:_gen_link_table_implementation()
    if self.data_encoder then self:_gen_node_data_implementation() end
    self:_gen_event_table_implementation()
    self:_gen_bitmask_table_implementation()
    self:_gen_kb_info_implementation()
end

