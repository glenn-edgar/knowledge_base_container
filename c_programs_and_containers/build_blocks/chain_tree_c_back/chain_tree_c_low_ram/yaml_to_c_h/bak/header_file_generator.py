"""
ChainTree YAML Handle - Data loader and organizer for header generation pipeline.

This class loads the YAML file generated by ChainTreeYaml and provides
organized access to all data needed for C header generation.
"""

import yaml
from pathlib import Path
from typing import Dict, List, Optional, Set


class ChainTreeYamlHandle:
    """
    Handle object for ChainTree YAML data.
    Loads and organizes data for the header generation pipeline.
    """
    
    def __init__(self, yaml_file: Path):
        """
        Load and organize ChainTree YAML data.
        
        Args:
            yaml_file: Path to the YAML file generated by ChainTreeYaml
        """
        self.yaml_file = yaml_file
        
        # Load raw YAML data
        with open(yaml_file, 'r') as f:
            self.raw_data = yaml.safe_load(f)
        
        # Extract top-level metadata
        self.kb_log_dict = self.raw_data.get('kb_log_dict', {})
        self.ltree_to_index = self.raw_data.get('ltree_to_index', {})
        self.total_nodes = self.raw_data.get('total_nodes', 0)
        
        # Organize nodes by knowledge base
        self.kb_nodes: Dict[str, Dict[str, Dict]] = {}  # kb_name -> {ltree_name -> node_data}
        self.kb_root_nodes: Dict[str, str] = {}  # kb_name -> root_ltree_name
        
        # Event and bitmask tables
        self.event_string_table: Dict[str, int] = {}
        self.bitmask_table: Dict[str, int] = {}
        
        # Function collections (all unique functions across all KBs)
        self.all_main_functions: Set[str] = set()
        self.all_one_shot_functions: Set[str] = set()
        self.all_boolean_functions: Set[str] = set()
        
        # Parse the YAML structure
        self._parse_yaml_data()
    
    def _parse_yaml_data(self) -> None:
        """Parse the raw YAML data into organized structures."""
        
        for ltree_name, node_data in self.raw_data.items():
            # Skip metadata entries
            if ltree_name in ['kb_log_dict', 'ltree_to_index', 'total_nodes']:
                continue
            
            # Skip non-dict entries
            if not isinstance(node_data, dict):
                continue
            
            # Parse ltree path
            parts = ltree_name.split('.')
            
            if len(parts) < 2 or parts[0] != 'kb':
                continue
            
            kb_name = parts[1]
            
            # Check for special tables
            if kb_name == 'event_string_table_kb':
                self._extract_event_string_table(ltree_name, node_data)
                continue
            
            if kb_name == 'bitmask_table_kb':
                self._extract_bitmask_table(ltree_name, node_data)
                continue
            
            # Initialize KB storage if needed
            if kb_name not in self.kb_nodes:
                self.kb_nodes[kb_name] = {}
            
            # Store node data
            self.kb_nodes[kb_name][ltree_name] = node_data
            
            # Track root node (shortest path for each KB)
            if kb_name not in self.kb_root_nodes or len(ltree_name) < len(self.kb_root_nodes[kb_name]):
                self.kb_root_nodes[kb_name] = ltree_name
            
            # Collect function names
            if 'label_dict' in node_data:
                label_dict = node_data['label_dict']
                
                main_fn = label_dict.get('main_function_name')
                if main_fn and main_fn != 'CFL_NULL':
                    self.all_main_functions.add(main_fn)
                
                init_fn = label_dict.get('initialization_function_name')
                term_fn = label_dict.get('termination_function_name')
                if init_fn and init_fn != 'CFL_NULL':
                    self.all_one_shot_functions.add(init_fn)
                if term_fn and term_fn != 'CFL_NULL':
                    self.all_one_shot_functions.add(term_fn)
                
                aux_fn = label_dict.get('aux_function_name')
                if aux_fn and aux_fn != 'CFL_NULL':
                    self.all_boolean_functions.add(aux_fn)
    
    def _extract_event_string_table(self, ltree_name: str, node_data: Dict) -> None:
        """Extract event string table from node data."""
        if 'node_dict' in node_data:
            self.event_string_table = node_data['node_dict'].copy()
    
    def _extract_bitmask_table(self, ltree_name: str, node_data: Dict) -> None:
        """Extract bitmask table from node data."""
        if 'node_dict' in node_data:
            self.bitmask_table = node_data['node_dict'].copy()
    
    # =========================================================================
    # Query Methods - Knowledge Bases
    # =========================================================================
    
    def get_kb_names(self) -> List[str]:
        """Get list of all knowledge base names."""
        return list(self.kb_nodes.keys())
    
    def get_kb_node_count(self, kb_name: str) -> int:
        """Get number of nodes in a knowledge base."""
        return len(self.kb_nodes.get(kb_name, {}))
    
    def get_kb_root_node(self, kb_name: str) -> Optional[str]:
        """Get the root node ltree name for a knowledge base."""
        return self.kb_root_nodes.get(kb_name)
    
    def get_kb_nodes(self, kb_name: str) -> Dict[str, Dict]:
        """Get all nodes for a knowledge base."""
        return self.kb_nodes.get(kb_name, {})
    
    # =========================================================================
    # Query Methods - Nodes
    # =========================================================================
    
    def get_node_data(self, ltree_name: str) -> Optional[Dict]:
        """Get node data for a specific ltree name."""
        for kb_nodes in self.kb_nodes.values():
            if ltree_name in kb_nodes:
                return kb_nodes[ltree_name]
        return None
    
    def get_node_index(self, ltree_name: str) -> Optional[int]:
        """Get the array index for a node."""
        return self.ltree_to_index.get(ltree_name)
    
    def get_node_parent(self, ltree_name: str) -> Optional[str]:
        """Get the parent ltree name for a node."""
        node_data = self.get_node_data(ltree_name)
        if node_data and 'label_dict' in node_data:
            return node_data['label_dict'].get('parent_ltree_name')
        return None
    
    def get_node_children(self, ltree_name: str) -> List[str]:
        """Get the child ltree names for a node."""
        node_data = self.get_node_data(ltree_name)
        if node_data and 'label_dict' in node_data:
            return node_data['label_dict'].get('links', [])
        return []
    
    def get_node_label(self, ltree_name: str) -> Optional[str]:
        """Get the label (node type) for a node."""
        node_data = self.get_node_data(ltree_name)
        if node_data:
            return node_data.get('label')
        return None
    
    def get_node_name(self, ltree_name: str) -> Optional[str]:
        """Get the node name for a node."""
        node_data = self.get_node_data(ltree_name)
        if node_data:
            return node_data.get('node_name')
        return None
    
    # =========================================================================
    # Query Methods - Functions
    # =========================================================================
    
    def get_node_functions(self, ltree_name: str) -> Dict[str, str]:
        """
        Get all function names for a node.
        
        Returns:
            Dictionary with keys: main, init, aux, term
        """
        node_data = self.get_node_data(ltree_name)
        if not node_data or 'label_dict' not in node_data:
            return {}
        
        label_dict = node_data['label_dict']
        return {
            'main': label_dict.get('main_function_name', 'CFL_NULL'),
            'init': label_dict.get('initialization_function_name', 'CFL_NULL'),
            'aux': label_dict.get('aux_function_name', 'CFL_NULL'),
            'term': label_dict.get('termination_function_name', 'CFL_NULL')
        }
    
    def get_all_functions(self) -> Dict[str, Set[str]]:
        """
        Get all unique functions across all knowledge bases.
        
        Returns:
            Dictionary with keys: main, one_shot, boolean
        """
        return {
            'main': self.all_main_functions.copy(),
            'one_shot': self.all_one_shot_functions.copy(),
            'boolean': self.all_boolean_functions.copy()
        }
    
    # =========================================================================
    # Query Methods - Event/Bitmask Tables
    # =========================================================================
    
    def get_event_string_table(self) -> Dict[str, int]:
        """Get the event string table (event_id -> index)."""
        return self.event_string_table.copy()
    
    def get_bitmask_table(self) -> Dict[str, int]:
        """Get the bitmask table (event_name -> bit_number)."""
        return self.bitmask_table.copy()
    
    def has_event_table(self) -> bool:
        """Check if event string table exists."""
        return len(self.event_string_table) > 0
    
    def has_bitmask_table(self) -> bool:
        """Check if bitmask table exists."""
        return len(self.bitmask_table) > 0
    
    # =========================================================================
    # Traversal Methods
    # =========================================================================
    
    def traverse_kb_breadth_first(self, kb_name: str) -> List[str]:
        """
        Traverse a knowledge base in breadth-first order starting from root.
        
        Args:
            kb_name: Knowledge base name
            
        Returns:
            List of ltree names in breadth-first order
        """
        root = self.get_kb_root_node(kb_name)
        if not root:
            return []
        
        result = []
        queue = [root]
        visited = set()
        
        while queue:
            current = queue.pop(0)
            
            if current in visited:
                continue
            
            visited.add(current)
            result.append(current)
            
            # Add children to queue
            children = self.get_node_children(current)
            for child in children:
                if child not in visited:
                    queue.append(child)
        
        return result
    
    def traverse_kb_depth_first(self, kb_name: str) -> List[str]:
        """
        Traverse a knowledge base in depth-first order starting from root.
        
        Args:
            kb_name: Knowledge base name
            
        Returns:
            List of ltree names in depth-first order
        """
        root = self.get_kb_root_node(kb_name)
        if not root:
            return []
        
        result = []
        visited = set()
        
        def dfs(node: str):
            if node in visited:
                return
            
            visited.add(node)
            result.append(node)
            
            # Visit children
            children = self.get_node_children(node)
            for child in children:
                dfs(child)
        
        dfs(root)
        return result
    
    # =========================================================================
    # Statistics and Validation
    # =========================================================================
    
    def get_statistics(self) -> Dict:
        """Get statistics about the loaded data."""
        stats = {
            'total_nodes': self.total_nodes,
            'kb_count': len(self.kb_nodes),
            'kb_details': {},
            'function_counts': {
                'main': len(self.all_main_functions),
                'one_shot': len(self.all_one_shot_functions),
                'boolean': len(self.all_boolean_functions)
            },
            'event_count': len(self.event_string_table),
            'bitmask_count': len(self.bitmask_table)
        }
        
        for kb_name in self.kb_nodes.keys():
            stats['kb_details'][kb_name] = {
                'node_count': self.get_kb_node_count(kb_name),
                'root_node': self.get_kb_root_node(kb_name)
            }
        
        return stats
    
    def validate(self) -> List[str]:
        """
        Validate the loaded data for consistency.
        
        Returns:
            List of validation error messages (empty if valid)
        """
        errors = []
        
        # Check that all nodes in ltree_to_index exist in node data
        for ltree_name, index in self.ltree_to_index.items():
            if not self.get_node_data(ltree_name):
                errors.append(f"Node in ltree_to_index not found in data: {ltree_name}")
        
        # Check that all parent references are valid
        for kb_name, kb_nodes in self.kb_nodes.items():
            for ltree_name, node_data in kb_nodes.items():
                if 'label_dict' in node_data:
                    parent = node_data['label_dict'].get('parent_ltree_name')
                    if parent and parent != '' and not self.get_node_data(parent):
                        errors.append(f"Invalid parent reference in {ltree_name}: {parent}")
                    
                    # Check that all children exist
                    children = node_data['label_dict'].get('links', [])
                    for child in children:
                        if not self.get_node_data(child):
                            errors.append(f"Invalid child reference in {ltree_name}: {child}")
        
        # Check total_nodes matches actual count
        actual_count = sum(len(nodes) for nodes in self.kb_nodes.values())
        if self.total_nodes != actual_count:
            errors.append(
                f"total_nodes mismatch: declared={self.total_nodes}, actual={actual_count}"
            )
        
        return errors
    
    def print_summary(self) -> None:
        """Print a summary of the loaded data."""
        print("=" * 70)
        print("ChainTree YAML Handle Summary")
        print("=" * 70)
        print(f"YAML File: {self.yaml_file}")
        print(f"Total Nodes: {self.total_nodes}")
        print(f"Knowledge Bases: {len(self.kb_nodes)}")
        
        for kb_name in self.kb_nodes.keys():
            node_count = self.get_kb_node_count(kb_name)
            root_node = self.get_kb_root_node(kb_name)
            print(f"  - {kb_name}: {node_count} nodes, root={root_node}")
        
        print(f"\nFunctions:")
        print(f"  Main functions: {len(self.all_main_functions)}")
        print(f"  One-shot functions: {len(self.all_one_shot_functions)}")
        print(f"  Boolean functions: {len(self.all_boolean_functions)}")
        
        if self.has_event_table():
            print(f"\nEvent String Table: {len(self.event_string_table)} events")
        
        if self.has_bitmask_table():
            print(f"Bitmask Table: {len(self.bitmask_table)} bitmasks")
        
        # Validation
        errors = self.validate()
        if errors:
            print(f"\n⚠ Validation Errors ({len(errors)}):")
            for error in errors:
                print(f"  - {error}")
        else:
            print("\n✓ Validation passed")
        
        print("=" * 70)


