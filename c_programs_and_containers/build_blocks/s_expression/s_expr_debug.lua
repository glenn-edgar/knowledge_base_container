-- ============================================================================
-- s_expr_debug.lua
-- S-Expression Engine Debug Output Generators - Version 5.2
-- 
-- Contains:
--   - generate_debug_header() - Debug header with hash->name mappings
--   - to_debug_dump() - Human-readable parameter dump
--
-- Loaded by s_expr_dsl.lua via dofile()
-- ============================================================================

local ffi = require("ffi")
local bit = require("bit")

local M = {}
local hash_module = nil
local types_module = nil

-- Called by s_expr_dsl.lua to inject dependencies
function M._init(hash, types)
    hash_module = hash
    types_module = types
end

-- ============================================================================
-- DEBUG HEADER GENERATOR
-- ============================================================================

function M.generate_debug_header(module)
    local lines = {}
    
    local guard = string.upper(module.name) .. "_DEBUG_H"
    local prefix = string.upper(module.name)
    
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// " .. module.name .. "_debug.h")
    table.insert(lines, "// DEBUG INFORMATION - Auto-generated by s_expr_dsl.lua v5.2")
    table.insert(lines, "// Module: " .. module.name)
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    table.insert(lines, "#ifndef " .. guard)
    table.insert(lines, "#define " .. guard)
    table.insert(lines, "")
    table.insert(lines, "#include <stdint.h>")
    table.insert(lines, "#include <stdio.h>")
    table.insert(lines, "")
    
    local tree_order = module.tree_order or {}
    local trees = module.trees or {}
    local record_order = module.record_order or {}
    local records = module.records or {}
    local oneshot_funcs = module.oneshot_funcs or {}
    local main_funcs = module.main_funcs or {}
    local pred_funcs = module.pred_funcs or {}
    
    -- Tree debug info
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// TREE DEBUG INFO")
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    table.insert(lines, "typedef struct {")
    table.insert(lines, "    uint32_t    hash;")
    table.insert(lines, "    const char* name;")
    table.insert(lines, "    uint16_t    node_count;")
    table.insert(lines, "    uint16_t    pointer_count;")
    table.insert(lines, "    uint16_t    param_count;")
    table.insert(lines, "} " .. module.name .. "_tree_debug_t;")
    table.insert(lines, "")
    
    table.insert(lines, "static const " .. module.name .. "_tree_debug_t " .. module.name .. "_tree_debug[] = {")
    if #tree_order > 0 then
        for i, tree_name in ipairs(tree_order) do
            local tree = trees[tree_name] or {}
            local name_hash = tree.name_hash or hash_module.fnv1a_32(tree_name)
            local node_count = tree.node_count or 0
            local pointer_count = tree.pointer_count or 0
            local param_count = tree.params and #tree.params or 0
            table.insert(lines, string.format(
                '    { 0x%08X, "%s", %d, %d, %d },',
                name_hash, tree_name, node_count, pointer_count, param_count
            ))
        end
    else
        table.insert(lines, '    { 0, "", 0, 0, 0 },  // Empty placeholder')
    end
    table.insert(lines, "};")
    table.insert(lines, string.format("#define %s_TREE_DEBUG_COUNT %d", prefix, math.max(1, #tree_order)))
    table.insert(lines, "")
    
    -- Function debug info
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// FUNCTION DEBUG INFO")
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    table.insert(lines, "typedef struct {")
    table.insert(lines, "    uint32_t    hash;")
    table.insert(lines, "    const char* name;")
    table.insert(lines, "    uint16_t    index;")
    table.insert(lines, "} " .. module.name .. "_func_debug_t;")
    table.insert(lines, "")
    
    local function emit_func_table(func_list, table_name, count_name)
        table.insert(lines, "static const " .. module.name .. "_func_debug_t " .. module.name .. "_" .. table_name .. "[] = {")
        if #func_list > 0 then
            for i, name in ipairs(func_list) do
                local h = hash_module.fnv1a_32(name)
                table.insert(lines, string.format(
                    '    { 0x%08X, "%s", %d },',
                    h, name, i - 1
                ))
            end
        else
            table.insert(lines, '    { 0, "", 0 },  // Empty placeholder')
        end
        table.insert(lines, "};")
        table.insert(lines, string.format("#define %s_%s %d", prefix, count_name, math.max(1, #func_list)))
        table.insert(lines, "")
    end
    
    table.insert(lines, "// Oneshot functions")
    emit_func_table(oneshot_funcs, "oneshot_debug", "ONESHOT_DEBUG_COUNT")
    
    table.insert(lines, "// Main functions")
    emit_func_table(main_funcs, "main_debug", "MAIN_DEBUG_COUNT")
    
    table.insert(lines, "// Predicate functions")
    emit_func_table(pred_funcs, "pred_debug", "PRED_DEBUG_COUNT")
    
    -- Record debug info
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// RECORD DEBUG INFO")
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    table.insert(lines, "typedef struct {")
    table.insert(lines, "    uint32_t    hash;")
    table.insert(lines, "    const char* name;")
    table.insert(lines, "    uint16_t    offset;")
    table.insert(lines, "    uint16_t    size;")
    table.insert(lines, "} " .. module.name .. "_field_debug_t;")
    table.insert(lines, "")
    table.insert(lines, "typedef struct {")
    table.insert(lines, "    uint32_t    hash;")
    table.insert(lines, "    const char* name;")
    table.insert(lines, "    uint16_t    size;")
    table.insert(lines, "    uint16_t    field_count;")
    table.insert(lines, "    const " .. module.name .. "_field_debug_t* fields;")
    table.insert(lines, "} " .. module.name .. "_record_debug_t;")
    table.insert(lines, "")
    
    -- Emit field tables for each record
    for _, record_name in ipairs(record_order) do
        local record = records[record_name] or {}
        local record_fields = record.fields or {}
        local field_table_name = module.name .. "_" .. string.lower(record_name) .. "_fields_debug"
        table.insert(lines, "static const " .. module.name .. "_field_debug_t " .. field_table_name .. "[] = {")
        if #record_fields > 0 then
            for _, field in ipairs(record_fields) do
                local field_name = field.name or "unknown"
                table.insert(lines, string.format(
                    '    { 0x%08X, "%s", %d, %d },',
                    hash_module.fnv1a_32(field_name), field_name, field.offset or 0, field.size or 0
                ))
            end
        else
            table.insert(lines, '    { 0, "", 0, 0 },  // Empty placeholder')
        end
        table.insert(lines, "};")
        table.insert(lines, "")
    end
    
    -- Emit record table
    table.insert(lines, "static const " .. module.name .. "_record_debug_t " .. module.name .. "_record_debug[] = {")
    if #record_order > 0 then
        for _, record_name in ipairs(record_order) do
            local record = records[record_name] or {}
            local record_fields = record.fields or {}
            local field_table_name = module.name .. "_" .. string.lower(record_name) .. "_fields_debug"
            table.insert(lines, string.format(
                '    { 0x%08X, "%s", %d, %d, %s },',
                hash_module.fnv1a_32(record_name), record_name, record.size or 0, #record_fields, field_table_name
            ))
        end
    else
        table.insert(lines, '    { 0, "", 0, 0, NULL },  // Empty placeholder')
    end
    table.insert(lines, "};")
    table.insert(lines, string.format("#define %s_RECORD_DEBUG_COUNT %d", prefix, math.max(1, #record_order)))
    table.insert(lines, "")
    
    -- Lookup functions
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// DEBUG LOOKUP FUNCTIONS")
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    
    table.insert(lines, "static inline const char* " .. module.name .. "_find_tree_name(uint32_t hash) {")
    table.insert(lines, "    for (int i = 0; i < " .. prefix .. "_TREE_DEBUG_COUNT; i++) {")
    table.insert(lines, "        if (" .. module.name .. "_tree_debug[i].hash == hash) return " .. module.name .. "_tree_debug[i].name;")
    table.insert(lines, "    }")
    table.insert(lines, '    return "UNKNOWN";')
    table.insert(lines, "}")
    table.insert(lines, "")
    
    table.insert(lines, "static inline const char* " .. module.name .. "_find_main_name(uint32_t hash) {")
    table.insert(lines, "    for (int i = 0; i < " .. prefix .. "_MAIN_DEBUG_COUNT; i++) {")
    table.insert(lines, "        if (" .. module.name .. "_main_debug[i].hash == hash) return " .. module.name .. "_main_debug[i].name;")
    table.insert(lines, "    }")
    table.insert(lines, '    return "UNKNOWN";')
    table.insert(lines, "}")
    table.insert(lines, "")
    
    table.insert(lines, "static inline const char* " .. module.name .. "_find_oneshot_name(uint32_t hash) {")
    table.insert(lines, "    for (int i = 0; i < " .. prefix .. "_ONESHOT_DEBUG_COUNT; i++) {")
    table.insert(lines, "        if (" .. module.name .. "_oneshot_debug[i].hash == hash) return " .. module.name .. "_oneshot_debug[i].name;")
    table.insert(lines, "    }")
    table.insert(lines, '    return "UNKNOWN";')
    table.insert(lines, "}")
    table.insert(lines, "")
    
    table.insert(lines, "static inline const char* " .. module.name .. "_find_pred_name(uint32_t hash) {")
    table.insert(lines, "    for (int i = 0; i < " .. prefix .. "_PRED_DEBUG_COUNT; i++) {")
    table.insert(lines, "        if (" .. module.name .. "_pred_debug[i].hash == hash) return " .. module.name .. "_pred_debug[i].name;")
    table.insert(lines, "    }")
    table.insert(lines, '    return "UNKNOWN";')
    table.insert(lines, "}")
    table.insert(lines, "")
    
    table.insert(lines, "static inline const char* " .. module.name .. "_find_record_name(uint32_t hash) {")
    table.insert(lines, "    for (int i = 0; i < " .. prefix .. "_RECORD_DEBUG_COUNT; i++) {")
    table.insert(lines, "        if (" .. module.name .. "_record_debug[i].hash == hash) return " .. module.name .. "_record_debug[i].name;")
    table.insert(lines, "    }")
    table.insert(lines, '    return "UNKNOWN";')
    table.insert(lines, "}")
    table.insert(lines, "")
    
    table.insert(lines, "#endif // " .. guard)
    table.insert(lines, "")
    
    return table.concat(lines, "\n")
end

function M.write_debug_header(module, output_path)
    local content = M.generate_debug_header(module)
    local path = output_path or "./" .. module.name .. "_debug.h"
    local f = io.open(path, "w")
    if f then
        f:write(content)
        f:close()
        print("Generated: " .. path)
    else
        error("Failed to write: " .. path)
    end
end

-- ============================================================================
-- PARAMETER DUMP GENERATOR
-- ============================================================================

function M.to_debug_dump(bin_gen, base_name)
    local lines = {}
    local mod = bin_gen.module
    local is_64bit = bin_gen.is_64bit
    local mode_suffix = is_64bit and "_64" or "_32"
    local guard = base_name:upper() .. "_DUMP" .. mode_suffix:upper() .. "_H"
    
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "// " .. base_name .. "_dump" .. mode_suffix .. ".h")
    table.insert(lines, "// DEBUG PARAMETER DUMP for " .. mod.name)
    table.insert(lines, "// Mode: " .. (is_64bit and "64-bit" or "32-bit"))
    table.insert(lines, "// Generated by s_expr_dsl v5.2")
    table.insert(lines, "// ============================================================================")
    table.insert(lines, "")
    table.insert(lines, "#ifndef " .. guard)
    table.insert(lines, "#define " .. guard)
    table.insert(lines, "")
    table.insert(lines, "/*")
    table.insert(lines, " * Module: " .. mod.name)
    table.insert(lines, " * Hash:   " .. hash_module.fmt_hash(mod.name_hash))
    table.insert(lines, " * Trees:  " .. #mod.tree_order)
    table.insert(lines, " * Records: " .. #mod.record_order)
    table.insert(lines, " * Strings: " .. #mod.string_table)
    table.insert(lines, " * Constants: " .. #mod.const_order)
    table.insert(lines, " */")
    table.insert(lines, "")
    
    -- String table dump
    if #mod.string_table > 0 then
        table.insert(lines, "// STRING TABLE")
        table.insert(lines, "/*")
        for i, s in ipairs(mod.string_table) do
            local escaped = s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n")
            table.insert(lines, string.format(" * [%2d] \"%s\"", i - 1, escaped))
        end
        table.insert(lines, " */")
        table.insert(lines, "")
    end
    
    -- Function tables dump
    table.insert(lines, "// FUNCTION TABLES")
    table.insert(lines, "/*")
    if #mod.oneshot_funcs > 0 then
        table.insert(lines, " * ONESHOT:")
        for i, name in ipairs(mod.oneshot_funcs) do
            table.insert(lines, string.format(" *   [%2d] %s", i - 1, name))
        end
    end
    if #mod.main_funcs > 0 then
        table.insert(lines, " * MAIN:")
        for i, name in ipairs(mod.main_funcs) do
            table.insert(lines, string.format(" *   [%2d] %s", i - 1, name))
        end
    end
    if #mod.pred_funcs > 0 then
        table.insert(lines, " * PRED:")
        for i, name in ipairs(mod.pred_funcs) do
            table.insert(lines, string.format(" *   [%2d] %s", i - 1, name))
        end
    end
    table.insert(lines, " */")
    table.insert(lines, "")
    
    -- Tree parameter dumps
    for _, tree_name in ipairs(mod.tree_order) do
        local tree = mod.trees[tree_name]
        
        table.insert(lines, "/*")
        table.insert(lines, string.format(" * TREE: %s (nodes=%d, ptrs=%d)", 
            tree_name, tree.node_count, tree.pointer_count or 0))
        table.insert(lines, " * IDX  TYPE              DETAILS")
        table.insert(lines, " * -------------------------------------------")
        
        local param_idx = 0
        
        local function dump_node(node, depth)
            local indent = string.rep("  ", depth)
            
            table.insert(lines, string.format(" * %3d  %sOPEN_CALL         %s",
                param_idx, indent, node.func_name))
            param_idx = param_idx + 1
            
            local func_type = node.call_type:upper():gsub("_CALL", "")
            table.insert(lines, string.format(" * %3d  %s  %-15s idx=%d",
                param_idx, indent, func_type, bin_gen:get_func_index(node)))
            param_idx = param_idx + 1
            
            -- Merge and sort params/children
            local items = {}
            for _, param in ipairs(node.params) do
                table.insert(items, { type = "param", order = param.order or 0, data = param })
            end
            for _, child in ipairs(node.children) do
                table.insert(items, { type = "child", order = child.order or 0, data = child })
            end
            table.sort(items, function(a, b) return a.order < b.order end)
            
            for _, item in ipairs(items) do
                if item.type == "child" then
                    dump_node(item.data, depth + 1)
                else
                    local p = item.data
                    local pi = indent .. "    "
                    local pt = p.type
                    local pv = p.value
                    
                    if pt == "int" then
                        table.insert(lines, string.format(" * %3d  %sINT               %d", param_idx, pi, pv))
                    elseif pt == "uint" then
                        table.insert(lines, string.format(" * %3d  %sUINT              %d", param_idx, pi, pv))
                    elseif pt == "float" then
                        table.insert(lines, string.format(" * %3d  %sFLOAT             %g", param_idx, pi, pv))
                    elseif pt == "str_idx" or pt == "str_ptr" then
                        table.insert(lines, string.format(" * %3d  %sSTR_IDX           \"%s\"", param_idx, pi, pv))
                    elseif pt == "str_hash" then
                        table.insert(lines, string.format(" * %3d  %sSTR_HASH          \"%s\"", param_idx, pi, pv.str))
                    elseif pt == "field_ref" or pt == "nested_field_ref" then
                        table.insert(lines, string.format(" * %3d  %sFIELD             %s", param_idx, pi, pv))
                    elseif pt == "const_ref" then
                        table.insert(lines, string.format(" * %3d  %sCONST_REF         %s", param_idx, pi, pv))
                    elseif pt == "dict_start" then
                        table.insert(lines, string.format(" * %3d  %sOPEN_DICT", param_idx, pi))
                    elseif pt == "dict_end" then
                        table.insert(lines, string.format(" * %3d  %sCLOSE_DICT", param_idx, pi))
                    elseif pt == "dict_key" then
                        table.insert(lines, string.format(" * %3d  %sOPEN_KEY          \"%s\"", param_idx, pi, pv))
                    elseif pt == "end_dict_key" then
                        table.insert(lines, string.format(" * %3d  %sCLOSE_KEY", param_idx, pi))
                    elseif pt == "list_start" then
                        table.insert(lines, string.format(" * %3d  %sOPEN", param_idx, pi))
                    elseif pt == "list_end" then
                        table.insert(lines, string.format(" * %3d  %sCLOSE", param_idx, pi))
                    else
                        table.insert(lines, string.format(" * %3d  %s%-17s %s", param_idx, pi, pt:upper(), tostring(pv)))
                    end
                    param_idx = param_idx + 1
                end
            end
            
            table.insert(lines, string.format(" * %3d  %sCLOSE             (end %s)", param_idx, indent, node.func_name))
            param_idx = param_idx + 1
        end
        
        for _, node in ipairs(tree.nodes) do
            dump_node(node, 0)
        end
        
        table.insert(lines, " */")
        table.insert(lines, "")
    end
    
    table.insert(lines, "#endif // " .. guard)
    
    return table.concat(lines, "\n")
end

