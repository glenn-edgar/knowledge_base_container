local function test_server_functions(server_path)
    print("rpc_server_path", server_path)
    print("initial state")

    print("clear server queue")
    kb:rpc_server_clear_server_queue(server_path)
    pp("list_jobs_job_types", kb:rpc_server_list_jobs_job_types(server_path, 'new_job'))

    local request_id1 = uuid4()
    kb:rpc_server_push_rpc_queue(server_path, request_id1, "rpc_action1",
        { data1 = "data1" }, "transaction_tag_1",
        { priority = 1, rpc_client_queue = "rpc_client_queue", max_retries = 5, wait_time = 0.5 })

    local request_id2 = uuid4()
    kb:rpc_server_push_rpc_queue(server_path, request_id2, "rpc_action2",
        { data2 = "data1" }, "transaction_tag_2",
        { priority = 2, rpc_client_queue = "rpc_client_queue", max_retries = 5, wait_time = 0.5 })

    pp("list_jobs_job_types", kb:rpc_server_list_jobs_job_types(server_path, 'new_job'))

    local request_id3 = uuid4()
    kb:rpc_server_push_rpc_queue(server_path, request_id3, "rpc_action3",
        { data3 = "data1" }, "transaction_tag_3",
        { priority = 3, rpc_client_queue = "rpc_client_queue", max_retries = 5, wait_time = 0.5 })

    pp("list_jobs_job_types", kb:rpc_server_list_jobs_job_types(server_path, 'new_job'))
    print("request_id", request_id1, request_id2, request_id3)
    pp("queued jobs", kb:rpc_server_list_jobs_job_types(server_path, 'new_job'))

    print("server_path", server_path)
    local job_data_1 = kb:rpc_server_peak_server_queue(server_path)
    pp("job_data_1", job_data_1)

    pp("count_all_jobs", kb:rpc_server_count_all_jobs(server_path))
    local job_data_2 = kb:rpc_server_peak_server_queue(server_path)
    pp("job_data_2", job_data_2)

    pp("count_all_jobs", kb:rpc_server_count_all_jobs(server_path))
    local job_data_3 = kb:rpc_server_peak_server_queue(server_path)
    pp("job_data_3", job_data_3)

    pp("count_all_jobs", kb:rpc_server_count_all_jobs(server_path))
    print("job_data_1.id", job_data_1.id)
