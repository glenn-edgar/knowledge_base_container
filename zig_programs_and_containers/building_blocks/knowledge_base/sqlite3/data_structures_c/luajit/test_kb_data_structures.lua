local function print_bit_data_class(data_class)
    print("  node_id", data_class.node_id)
    print("  user_name", data_class.user_name)
    pp("  flags", data_class.flags)
    print("  bit_size", data_class.bit_size)
    print("  bit_mask", data_class.bit_mask)
    pp("  flag_data", data_class.flag_data)
    pp("  flag_change", data_class.flag_change)
end

local function test_bit_structures()
    print("***************************  Bit Structures ***************************")

    local node_ids = kb:find_bit_structure_ids({ node_name = "info1_bit_mask" })
    local properties = json.decode(node_ids[1].properties)
    local node_id = properties.record_id
    kb:set_all_ones(node_id)
    kb:set_all_zeros(node_id)

    local bit_data = kb:find_assemble_bit_data(node_ids, false, { "user_1" })

    local data_class
    for user_name, dc in pairs(bit_data) do
        print("@@@@@@@@@@@  user_name", user_name)
        print_bit_data_class(dc)
        data_class = dc
    end

    kb:set_flag_data(data_class, { F = 1, G = 0, H = 0, I = 0, J = 0 })
    kb:get_flag_data(data_class)
    print_bit_data_class(data_class)

    kb:set_flag_data(data_class, { J = 1 })
    kb:get_flag_data(data_class)
    print_bit_data_class(data_class)

    local sexpr = "(or (and user_1:F user_1:G user_1:H user_1:I user_1:J) (and user_1:F user_1:J))"
    print("s-expression", sexpr)
    local tokens = kb:s_tokenize(sexpr)
    local result = kb:s_execute(tokens, bit_data)
    print("result", result)

    local expr2 = "(bit_changed  user_1:J)"
    print("expression", expr2)
    tokens = kb:s_tokenize(expr2)
    result = kb:s_execute(tokens, bit_data)
    print("result", result)

    local expr3 = "(bit_changed  user_1:F)"
    print("expression", expr3)
    tokens = kb:s_tokenize(expr3)
    result = kb:s_execute(tokens, bit_data)
    print("result", result)

    print("***************************  Bit Structures test complete ***************************")
end

