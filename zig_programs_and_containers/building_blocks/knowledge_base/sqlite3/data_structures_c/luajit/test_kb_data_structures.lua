--- Simple UUID4 for test request IDs
local function uuid4()
    local rng = math.random
    local function r4() return string.format('%04x', rng(0, 0xffff)) end
    return string.format('%s%s-%s-4%s-%s%s-%s%s%s',
        r4(), r4(), r4(),
        string.format('%03x', rng(0, 0x0fff)),
        string.format('%x', rng(8, 11)) .. string.format('%03x', rng(0, 0x0fff)),
        '', r4(), r4(), r4())
end

--- Pretty-print a table (shallow)
local function pp(label, val)
    if type(val) == 'table' then
        print(label, json.encode(val))
    else
        print(label, tostring(val))
    end
end

--- ISO timestamp for "now minus N minutes"
local function utc_minutes_ago(minutes)
    return os.date('!%Y-%m-%dT%H:%M:%S', os.time() - minutes * 60)
end
local function utc_now()
    return os.date('!%Y-%m-%dT%H:%M:%S')
end

