local function test_client_queue(client_path)
    print("=== Initial State ===")
    local free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    local queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    local waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    kb:rpc_client_clear_reply_queue(client_path)
    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Push first set of reply data
    print("\n=== Pushing First Set of Reply Data ===")
    local request_id1 = uuid4()
    kb:rpc_client_push_and_claim_reply_data(
        client_path, request_id1, "xxx", "Action1", "xxx", { data1 = "data1" })
    print("Pushed reply data with request ID: " .. request_id1)

    local request_id2 = uuid4()
    kb:rpc_client_push_and_claim_reply_data(
        client_path, request_id2, "xxx", "Action2", "yyy", { data2 = "data2" })
    print("Pushed reply data with request ID: " .. request_id2)

    -- After first push
    print("\n=== After First Push ===")
    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Peek and release first data
    print("\n=== Peek and Release First Data ===")
    local peak_data = kb:rpc_client_peak_and_claim_reply_data(client_path)
    pp("Peek data:", peak_data)

    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Additional queue check
    print("\n=== Additional Queue Check ===")
    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Peek and release second data
    print("\n=== Peek and Release Second Data ===")
    peak_data = kb:rpc_client_peak_and_claim_reply_data(client_path)
    pp("Peek data:", peak_data)

    -- After second release
    print("\n=== After Second Release ===")
    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Push second set of reply data
    print("\n=== Pushing Second Set of Reply Data ===")
    local request_id3 = uuid4()
    kb:rpc_client_push_and_claim_reply_data(
        client_path, request_id3, "xxx", "Action1", "xxx", { data1 = "data1" })
    print("Pushed reply data with request ID: " .. request_id3)

    local request_id4 = uuid4()
    kb:rpc_client_push_and_claim_reply_data(
        client_path, request_id4, "xxx", "Action2", "yyy", { data2 = "data2" })
    print("Pushed reply data with request ID: " .. request_id4)

    -- After second push
    print("\n=== After Second Push ===")
    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    -- Clear reply queue
    print("\n=== Clearing Reply Queue ===")
    kb:rpc_client_clear_reply_queue(client_path)
    print("Cleared reply queue for client path: " .. client_path)

    -- Final state
    print("\n=== Final State After Clear ===")
    free_slots = kb:rpc_client_find_free_slots(client_path)
    print(string.format("Number of free slots: %d", free_slots))

    queued_slots = kb:rpc_client_find_queued_slots(client_path)
    print(string.format("Number of queued slots: %d", queued_slots))

    waiting_jobs = kb:rpc_client_list_waiting_jobs(client_path)
    pp("Waiting jobs:", waiting_jobs)

    print("\n=== Test Complete ===")
end

